%% ========================================================================
% PAPER 3 — STEP 6
% FULL 130-SUBJECT BAD-CHANNEL + 11-REGION COVERAGE AUDIT
%
% PURPOSE
% -------
% Before full-cohort ICA/connectivity:
%
%   1. Identify bad EEG channels using the FINAL revised rule.
%   2. Count how frequently every electrode is bad across the cohort.
%   3. Check whether any electrode is systematically bad.
%   4. Quantify usable electrode coverage for each of 11 predefined regions.
%   5. Do NOT yet impose a regional exclusion threshold.
%
% COHORT
% ------
% Starting paired Rest+Walk cohort = 133
%
% Temporarily exclude unresolved abnormal walking recordings:
%       sub-104
%       sub-110
%       sub-123
%
% Expected analysis audit cohort:
%       23 HC + 107 PD = 130
%
% sub-064:
%       retain using event-defined walking block:
%       662.592 to 906.196 s
%
%
% FINAL BAD-CHANNEL RULE
% ----------------------
%
% HIGH-NOISE:
%       robust-z(log10 SD) > +5
%       AND
%       SD / median(channel SD) > 3
%
% NEAR-FLAT:
%       SD / median(channel SD) < 0.05
%
% NON-FINITE:
%       reject
%
% LOW AMPLITUDE REVIEW:
%       0.05 <= SD ratio < 0.20
%       review only; NOT rejected
%
% A channel bad in either Rest OR Walk is marked bad for the subject
% in BOTH conditions.
%
%
% 11 REGIONS
% ----------
%
% Original dataset-author definitions are retained except:
%
%       O1 + Oz + O2
%
% are combined into ONE Occipital region.
%
% NO PCA.
% NO interpolation.
% NO ICA.
% NO connectivity.
%
% This script only audits channel/region availability.
%% ========================================================================

clear;
clc;
close all;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();
addpath(cfg.fieldtripRoot);

ft_defaults;

%% ========================================================================
% 1. PATHS
%% ========================================================================

rootdir = ...
    cfg.datasetRoot;

participantsFile = ...
    fullfile(rootdir,'participants.tsv');

outdir = ...
    fullfile(rootdir,'PAPER3_FULL130_BADCHANNEL_AUDIT');

if ~exist(outdir,'dir')
    mkdir(outdir);
end

if ~exist(participantsFile,'file')
    error('participants.tsv not found:\n%s',participantsFile);
end

%% ========================================================================
% 2. FROZEN BAD-CHANNEL PARAMETERS
%% ========================================================================

Z_HIGH = 5.0;

HIGH_RATIO = 3.0;

FLAT_RATIO = 0.05;

LOW_REVIEW_RATIO = 0.20;

%% ========================================================================
% 3. SUBJECTS TEMPORARILY EXCLUDED
%
% These three have unresolved abnormal-length WALK recordings.
%% ========================================================================

manualExclude = [ ...
    "sub-104"
    "sub-110"
    "sub-123"
    ];

%% ========================================================================
% 4. SPECIAL WALK SEGMENT
%% ========================================================================

specialSubject = "sub-064";

specialWalkStart = 662.592;
specialWalkEnd   = 906.196;

%% ========================================================================
% 5. LOAD PARTICIPANT METADATA
%% ========================================================================

P = readtable( ...
    participantsFile, ...
    'FileType','text', ...
    'Delimiter','\t', ...
    'TextType','string', ...
    'VariableNamingRule','preserve');

if ~ismember('participant_id',P.Properties.VariableNames)
    error('participant_id column not found in participants.tsv');
end

if ~ismember('group',P.Properties.VariableNames)
    error('group column not found in participants.tsv');
end

participantID = string(P.participant_id);
participantGroup = string(P.group);

%% ========================================================================
% 6. FIND SUBJECTS WITH BOTH REST AND WALK
%% ========================================================================

hasRest = false(height(P),1);
hasWalk = false(height(P),1);

for i = 1:height(P)

    subj = participantID(i);

    eegdir = fullfile( ...
        rootdir, ...
        char(subj), ...
        'eeg');

    restfile = fullfile( ...
        eegdir, ...
        char(subj) + "_task-rest_eeg.set");

    walkfile = fullfile( ...
        eegdir, ...
        char(subj) + "_task-walk_eeg.set");

    hasRest(i) = exist(restfile,'file') == 2;
    hasWalk(i) = exist(walkfile,'file') == 2;

end

pairedMask = ...
    hasRest & ...
    hasWalk;

pairedSubjects = participantID(pairedMask);
pairedGroups   = participantGroup(pairedMask);

fprintf('\n============================================================\n');
fprintf('PAIRED REST + WALK COHORT\n');
fprintf('============================================================\n');

fprintf('Paired subjects = %d\n',numel(pairedSubjects));

fprintf('HC = %d\n',sum(pairedGroups=="HC"));
fprintf('PD = %d\n',sum(pairedGroups=="PD"));

%% ========================================================================
% 7. BUILD FINAL 130-SUBJECT AUDIT COHORT
%% ========================================================================

keepMask = ...
    pairedMask & ...
    ~ismember(participantID,manualExclude);

subjects = participantID(keepMask);
groups   = participantGroup(keepMask);

N = numel(subjects);

fprintf('\n============================================================\n');
fprintf('FULL BAD-CHANNEL AUDIT COHORT\n');
fprintf('============================================================\n');

fprintf('Subjects = %d\n',N);
fprintf('HC       = %d\n',sum(groups=="HC"));
fprintf('PD       = %d\n',sum(groups=="PD"));

fprintf('\nTemporarily excluded:\n');
disp(manualExclude);

%% HARD SAFETY CHECK

if N ~= 130

    error([ ...
        'Expected exactly 130 subjects but found %d.\n' ...
        'STOP and inspect cohort construction before continuing.'], ...
        N);

end

if sum(groups=="HC") ~= 23

    warning( ...
        'Expected 23 HC but found %d.', ...
        sum(groups=="HC"));

end

if sum(groups=="PD") ~= 107

    warning( ...
        'Expected 107 PD but found %d.', ...
        sum(groups=="PD"));

end

%% Save exact audit cohort

Cohort = table( ...
    subjects, ...
    groups, ...
    'VariableNames', ...
    {'Subject','Group'});

writetable( ...
    Cohort, ...
    fullfile(outdir,'Paper3_130_subject_cohort.csv'));

%% ========================================================================
% 8. DEFINE EXACT 60 EEG CHANNELS
%% ========================================================================

allEEG = [ ...

    "F10","AF4","F2","FCz","Fp2","Fz","FC1","AFz","F1","Fp1", ...
    "AF3","F3","F5","FC5","FC3","C1","F9","F7","FT7","C3", ...
    "CP1","C5","T9","T7","TP7","CP5","P5","P3","TP9","P7", ...
    "P1","P9","PO3","Pz","O1","POz","Oz","PO4","O2","P2", ...
    "CP2","P4","P10","P8","P6","CP6","TP10","TP8","C6","C4", ...
    "C2","T8","FC4","FC2","T10","FT8","FC6","F8","F6","F4" ...
    ]';

if numel(allEEG) ~= 60
    error('Expected 60 EEG channels.');
end

%% ========================================================================
% 9. DEFINE FINAL 11-REGION MAP
%% ========================================================================

regionNames = [ ...
    "FrontalLeft"
    "FrontalMidline"
    "FrontalRight"
    "CentralLeft"
    "CentralRight"
    "ParietalLeft"
    "ParietalMidline"
    "ParietalRight"
    "TemporalLeft"
    "TemporalRight"
    "Occipital"
    ];

regionChannels = cell(11,1);

regionChannels{1} = [ ...
    "F1","F9","Fp1","FC5","AF3","F7", ...
    "F5","F3","FT7","FC3","FC1"];

regionChannels{2} = [ ...
    "AFz","Fz","FCz"];

regionChannels{3} = [ ...
    "Fp2","AF4","F10","F2","F4","F6", ...
    "F8","FC2","FC4","FC6","FT8"];

regionChannels{4} = [ ...
    "C1","C3","C5"];

regionChannels{5} = [ ...
    "C2","C4","C6"];

regionChannels{6} = [ ...
    "CP1","CP5","P1","P3","P5","P7","P9","PO3"];

regionChannels{7} = [ ...
    "Pz","POz"];

regionChannels{8} = [ ...
    "CP2","CP6","P2","P4","P6","P8","P10","PO4"];

regionChannels{9} = [ ...
    "T7","TP7","T9","TP9"];

regionChannels{10} = [ ...
    "T8","TP8","T10","TP10"];

% Combined occipital ROI
regionChannels{11} = [ ...
    "O1","Oz","O2"];

%% ========================================================================
% 10. VERIFY REGION MAP
%% ========================================================================

mappedChannels = strings(0,1);

for r = 1:numel(regionNames)

    mappedChannels = [ ...
        mappedChannels; ...
        regionChannels{r}(:)];

end

if numel(mappedChannels) ~= 60

    error( ...
        'Region mapping contains %d entries, expected 60.', ...
        numel(mappedChannels));

end

if numel(unique(mappedChannels)) ~= 60

    error('Duplicate channels found in regional mapping.');

end

missingFromMap = ...
    setdiff(allEEG,mappedChannels);

extraInMap = ...
    setdiff(mappedChannels,allEEG);

if ~isempty(missingFromMap) || ~isempty(extraInMap)

    fprintf('\nMissing from region map:\n');
    disp(missingFromMap);

    fprintf('\nExtra in region map:\n');
    disp(extraInMap);

    error('11-region map does not match the 60-channel montage.');

end

fprintf('\n11-region map verified: all 60 EEG channels assigned exactly once.\n');

%% Save ROI definition

ROIName = strings(0,1);
Channel = strings(0,1);

for r = 1:numel(regionNames)

    nr = numel(regionChannels{r});

    ROIName = [ ...
        ROIName; ...
        repmat(regionNames(r),nr,1)];

    Channel = [ ...
        Channel; ...
        regionChannels{r}(:)];

end

ROIMap = table(ROIName,Channel);

writetable( ...
    ROIMap, ...
    fullfile(outdir,'Paper3_11region_channel_map.csv'));

%% ========================================================================
% 11. STORAGE
%% ========================================================================

Subject = subjects;
Group   = groups;

Status = repmat("NOT_RUN",N,1);

RestDurationSec = nan(N,1);
WalkDurationSec = nan(N,1);

NBadChannels = nan(N,1);
NHighNoise   = nan(N,1);
NNearFlat    = nan(N,1);
NNonFinite   = nan(N,1);
NLowReview   = nan(N,1);

BadChannelLabels = repmat("",N,1);
LowReviewLabels  = repmat("",N,1);

%% Long tables

ChannelAudit = table();

RegionAudit = table();

%% ========================================================================
% 12. SUBJECT LOOP
%% ========================================================================

for s = 1:N

    subj = subjects(s);
    grp  = groups(s);

    fprintf('\n\n');
    fprintf('############################################################\n');
    fprintf('SUBJECT %d / %d — %s — %s\n', ...
        s,N,subj,grp);
    fprintf('############################################################\n');

    try

        %% ================================================================
        % FILES
        %% ================================================================

        eegdir = fullfile( ...
            rootdir, ...
            char(subj), ...
            'eeg');

        restfile = fullfile( ...
            eegdir, ...
            char(subj) + "_task-rest_eeg.set");

        walkfile = fullfile( ...
            eegdir, ...
            char(subj) + "_task-walk_eeg.set");

        %% ================================================================
        % LOAD REST
        %% ================================================================

        cfg = [];
        cfg.dataset = restfile;

        restAll = ...
            ft_preprocessing(cfg);

        %% ================================================================
        % LOAD WALK
        %% ================================================================

        cfg = [];
        cfg.dataset = walkfile;

        walkAll = ...
            ft_preprocessing(cfg);

        %% ================================================================
        % SPECIAL sub-064 WALK SEGMENT
        %% ================================================================

        if subj == specialSubject

            fprintf('\nSPECIAL sub-064 WALK segmentation:\n');
            fprintf('Using %.3f to %.3f s\n', ...
                specialWalkStart, ...
                specialWalkEnd);

            availableStart = ...
                walkAll.time{1}(1);

            availableEnd = ...
                walkAll.time{1}(end);

            fprintf('Available WALK time = %.3f to %.3f s\n', ...
                availableStart, ...
                availableEnd);

            if specialWalkStart < availableStart || ...
               specialWalkEnd > availableEnd

                error( ...
                    ['sub-064 requested walking interval lies outside ' ...
                     'available time range.']);

            end

            cfg = [];
            cfg.latency = [ ...
                specialWalkStart ...
                specialWalkEnd];

            walkAll = ...
                ft_selectdata(cfg,walkAll);

        end

        %% ================================================================
        % VERIFY 250-Hz SAMPLING
        %% ================================================================

        if abs(restAll.fsample-250) > 1e-6 || ...
           abs(walkAll.fsample-250) > 1e-6

            error( ...
                'Unexpected sampling frequency Rest=%.6f Walk=%.6f', ...
                restAll.fsample, ...
                walkAll.fsample);

        end

        RestDurationSec(s) = ...
            size(restAll.trial{1},2) / ...
            restAll.fsample;

        WalkDurationSec(s) = ...
            size(walkAll.trial{1},2) / ...
            walkAll.fsample;

        fprintf('REST duration = %.2f s\n', ...
            RestDurationSec(s));

        fprintf('WALK duration = %.2f s\n', ...
            WalkDurationSec(s));

        %% ================================================================
        % SELECT EXACT 60 EEG CHANNELS
        %% ================================================================

        restLabels = ...
            string(restAll.label);

        walkLabels = ...
            string(walkAll.label);

        missingR = ...
            setdiff(allEEG,restLabels);

        missingW = ...
            setdiff(allEEG,walkLabels);

        if ~isempty(missingR)

            fprintf('Missing REST EEG labels:\n');
            disp(missingR);

            error('REST missing expected EEG channels.');

        end

        if ~isempty(missingW)

            fprintf('Missing WALK EEG labels:\n');
            disp(missingW);

            error('WALK missing expected EEG channels.');

        end

        cfg = [];
        cfg.channel = cellstr(allEEG);

        restEEG = ...
            ft_selectdata(cfg,restAll);

        walkEEG = ...
            ft_selectdata(cfg,walkAll);

        %% Confirm exact order

        if ~isequal( ...
                string(restEEG.label), ...
                allEEG)

            error('REST EEG channel order mismatch.');

        end

        if ~isequal( ...
                string(walkEEG.label), ...
                allEEG)

            error('WALK EEG channel order mismatch.');

        end

        %% ================================================================
        % FINAL FROZEN FILTERING
        %% ================================================================

        cfg = [];

        cfg.hpfilter   = 'yes';
        cfg.hpfreq     = 1;
        cfg.hpfilttype = 'but';
        cfg.hpfiltord  = 4;
        cfg.hpfiltdir  = 'twopass';

        cfg.lpfilter   = 'yes';
        cfg.lpfreq     = 45;
        cfg.lpfilttype = 'but';
        cfg.lpfiltord  = 4;
        cfg.lpfiltdir  = 'twopass';

        cfg.dftfilter = 'yes';
        cfg.dftfreq   = 50;

        cfg.demean = 'yes';

        restFilt = ...
            ft_preprocessing(cfg,restEEG);

        walkFilt = ...
            ft_preprocessing(cfg,walkEEG);

        %% ================================================================
        % DATA MATRICES
        %% ================================================================

        XR = ...
            double(restFilt.trial{1});

        XW = ...
            double(walkFilt.trial{1});

        %% ================================================================
        % CHANNEL SD
        %% ================================================================

        sdR = ...
            std(XR,0,2);

        sdW = ...
            std(XW,0,2);

        medSdR = ...
            median(sdR,'omitnan');

        medSdW = ...
            median(sdW,'omitnan');

        ratioR = ...
            sdR ./ ...
            (medSdR + eps);

        ratioW = ...
            sdW ./ ...
            (medSdW + eps);

        %% ================================================================
        % ROBUST Z OF log10(SD)
        %% ================================================================

        zR = ...
            robust_z(log10(sdR));

        zW = ...
            robust_z(log10(sdW));

        %% ================================================================
        % FINAL HIGH-NOISE RULE
        %% ================================================================

        highR = ...
            zR > Z_HIGH & ...
            ratioR > HIGH_RATIO;

        highW = ...
            zW > Z_HIGH & ...
            ratioW > HIGH_RATIO;

        highNoise = ...
            highR | highW;

        %% ================================================================
        % FINAL NEAR-FLAT RULE
        %% ================================================================

        flatR = ...
            ratioR < FLAT_RATIO;

        flatW = ...
            ratioW < FLAT_RATIO;

        nearFlat = ...
            flatR | flatW;

        %% ================================================================
        % NON-FINITE
        %% ================================================================

        nonFiniteR = ...
            any(~isfinite(XR),2);

        nonFiniteW = ...
            any(~isfinite(XW),2);

        nonFinite = ...
            nonFiniteR | ...
            nonFiniteW;

        %% ================================================================
        % FINAL SUBJECT BAD CHANNELS
        %% ================================================================

        badMask = ...
            highNoise | ...
            nearFlat | ...
            nonFinite;

        %% ================================================================
        % LOW-AMPLITUDE REVIEW ONLY
        %% ================================================================

        lowReviewMask = ...
            (ratioR < LOW_REVIEW_RATIO | ...
             ratioW < LOW_REVIEW_RATIO) & ...
            ~nearFlat & ...
            ~badMask;

        badLabels = ...
            allEEG(badMask);

        lowReviewLabels = ...
            allEEG(lowReviewMask);

        %% Subject summary

        NBadChannels(s) = ...
            sum(badMask);

        NHighNoise(s) = ...
            sum(highNoise);

        NNearFlat(s) = ...
            sum(nearFlat);

        NNonFinite(s) = ...
            sum(nonFinite);

        NLowReview(s) = ...
            sum(lowReviewMask);

        if isempty(badLabels)

            BadChannelLabels(s) = ...
                "NONE";

        else

            BadChannelLabels(s) = ...
                strjoin(badLabels,",");

        end

        if isempty(lowReviewLabels)

            LowReviewLabels(s) = ...
                "NONE";

        else

            LowReviewLabels(s) = ...
                strjoin(lowReviewLabels,",");

        end

        fprintf('\nBad channels = %d\n', ...
            NBadChannels(s));

        if ~isempty(badLabels)
            disp(badLabels);
        end

        %% ================================================================
        % CHANNEL-LEVEL LONG TABLE
        %% ================================================================

        thisChannel = table( ...
            repmat(subj,60,1), ...
            repmat(grp,60,1), ...
            allEEG, ...
            sdR, ...
            sdW, ...
            ratioR, ...
            ratioW, ...
            zR, ...
            zW, ...
            highNoise, ...
            nearFlat, ...
            nonFinite, ...
            lowReviewMask, ...
            badMask, ...
            'VariableNames', ...
            {'Subject', ...
             'Group', ...
             'Channel', ...
             'RestSD', ...
             'WalkSD', ...
             'RestSDRatio', ...
             'WalkSDRatio', ...
             'RestRobustZ', ...
             'WalkRobustZ', ...
             'HighNoise', ...
             'NearFlat', ...
             'NonFinite', ...
             'LowReview', ...
             'BadChannel'});

        ChannelAudit = [ ...
            ChannelAudit; ...
            thisChannel];

        %% ================================================================
        % 11-REGION COVERAGE
        %% ================================================================

        for r = 1:numel(regionNames)

            reg = regionNames(r);

            regChannels = ...
                regionChannels{r};

            idx = ...
                ismember(allEEG,regChannels);

            nDefined = ...
                sum(idx);

            nBad = ...
                sum(badMask(idx));

            nGood = ...
                nDefined - nBad;

            nReview = ...
                sum(lowReviewMask(idx));

            coverage = ...
                nGood / nDefined;

            badInRegion = ...
                allEEG(idx & badMask);

            goodInRegion = ...
                allEEG(idx & ~badMask);

            if isempty(badInRegion)
                badText = "NONE";
            else
                badText = ...
                    strjoin(badInRegion,",");
            end

            if isempty(goodInRegion)
                goodText = "NONE";
            else
                goodText = ...
                    strjoin(goodInRegion,",");
            end

            thisRegion = table( ...
                subj, ...
                grp, ...
                reg, ...
                nDefined, ...
                nGood, ...
                nBad, ...
                nReview, ...
                coverage, ...
                goodText, ...
                badText, ...
                'VariableNames', ...
                {'Subject', ...
                 'Group', ...
                 'Region', ...
                 'NDefined', ...
                 'NGood', ...
                 'NBad', ...
                 'NLowReview', ...
                 'CoverageFraction', ...
                 'GoodChannels', ...
                 'BadChannels'});

            RegionAudit = [ ...
                RegionAudit; ...
                thisRegion];

        end

        Status(s) = "PASS";

        %% ================================================================
        % SAVE PROGRESS AFTER EACH SUBJECT
        %% ================================================================

        SubjectSummary = table( ...
            Subject, ...
            Group, ...
            RestDurationSec, ...
            WalkDurationSec, ...
            NBadChannels, ...
            NHighNoise, ...
            NNearFlat, ...
            NNonFinite, ...
            NLowReview, ...
            BadChannelLabels, ...
            LowReviewLabels, ...
            Status);

        writetable( ...
            SubjectSummary, ...
            fullfile( ...
            outdir, ...
            'Paper3_130_badchannel_subject_summary_PROGRESS.csv'));

        writetable( ...
            ChannelAudit, ...
            fullfile( ...
            outdir, ...
            'Paper3_130_channel_audit_PROGRESS.csv'));

        writetable( ...
            RegionAudit, ...
            fullfile( ...
            outdir, ...
            'Paper3_130_region_coverage_PROGRESS.csv'));

    catch ME

        Status(s) = "ERROR";

        fprintf('\n**************** ERROR ****************\n');
        fprintf('%s\n',ME.message);
        fprintf('****************************************\n');

        errorFile = ...
            fullfile( ...
            outdir, ...
            char(subj) + "_AUDIT_ERROR.txt");

        fid = fopen(errorFile,'w');

        fprintf( ...
            fid, ...
            '%s\n', ...
            getReport( ...
                ME, ...
                'extended', ...
                'hyperlinks','off'));

        fclose(fid);

    end

end

%% ========================================================================
% 13. FINAL SUBJECT SUMMARY
%% ========================================================================

SubjectSummary = table( ...
    Subject, ...
    Group, ...
    RestDurationSec, ...
    WalkDurationSec, ...
    NBadChannels, ...
    NHighNoise, ...
    NNearFlat, ...
    NNonFinite, ...
    NLowReview, ...
    BadChannelLabels, ...
    LowReviewLabels, ...
    Status);

subjectFile = ...
    fullfile( ...
    outdir, ...
    'Paper3_130_badchannel_subject_summary.csv');

writetable( ...
    SubjectSummary, ...
    subjectFile);

%% ========================================================================
% 14. VERIFY ALL 130 COMPLETED
%% ========================================================================

fprintf('\n\n');
fprintf('============================================================\n');
fprintf('AUDIT PROCESSING STATUS\n');
fprintf('============================================================\n');

disp(groupsummary( ...
    SubjectSummary, ...
    {'Group','Status'}));

if any(Status=="ERROR")

    fprintf('\nERROR SUBJECTS:\n');

    disp( ...
    SubjectSummary( ...
        Status == "ERROR", ...
        {'Subject','Group','Status'}));

    warning( ...
        'Some subjects failed. Do NOT freeze coverage rules yet.');

end

%% ========================================================================
% 15. SAVE COMPLETE CHANNEL + REGION LONG TABLES
%% ========================================================================

channelLongFile = ...
    fullfile( ...
    outdir, ...
    'Paper3_130_channel_badchannel_long.csv');

writetable( ...
    ChannelAudit, ...
    channelLongFile);

regionLongFile = ...
    fullfile( ...
    outdir, ...
    'Paper3_130_region_coverage_long.csv');

writetable( ...
    RegionAudit, ...
    regionLongFile);

%% ========================================================================
% 16. CHANNEL BAD-FREQUENCY SUMMARY
%% ========================================================================

goodSubjectMask = ...
    Status == "PASS";

Npass = ...
    sum(goodSubjectMask);

NHC = ...
    sum(Group=="HC" & goodSubjectMask);

NPD = ...
    sum(Group=="PD" & goodSubjectMask);

ChannelName = allEEG;

BadN_All = nan(60,1);
BadPct_All = nan(60,1);

BadN_HC = nan(60,1);
BadPct_HC = nan(60,1);

BadN_PD = nan(60,1);
BadPct_PD = nan(60,1);

ReviewN_All = nan(60,1);
ReviewPct_All = nan(60,1);

for ch = 1:60

    label = allEEG(ch);

    idxAll = ...
        ChannelAudit.Channel == label;

    idxHC = ...
        idxAll & ...
        ChannelAudit.Group == "HC";

    idxPD = ...
        idxAll & ...
        ChannelAudit.Group == "PD";

    BadN_All(ch) = ...
        sum(ChannelAudit.BadChannel(idxAll));

    BadPct_All(ch) = ...
        100 * BadN_All(ch) / ...
        sum(idxAll);

    BadN_HC(ch) = ...
        sum(ChannelAudit.BadChannel(idxHC));

    BadPct_HC(ch) = ...
        100 * BadN_HC(ch) / ...
        max(sum(idxHC),1);

    BadN_PD(ch) = ...
        sum(ChannelAudit.BadChannel(idxPD));

    BadPct_PD(ch) = ...
        100 * BadN_PD(ch) / ...
        max(sum(idxPD),1);

    ReviewN_All(ch) = ...
        sum(ChannelAudit.LowReview(idxAll));

    ReviewPct_All(ch) = ...
        100 * ReviewN_All(ch) / ...
        sum(idxAll);

end

MajorityBad = ...
    BadPct_All > 50;

