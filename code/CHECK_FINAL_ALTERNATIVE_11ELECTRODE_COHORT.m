%% =========================================================================
% PAPER 3
% FINAL COHORT CHECK FOR FROZEN ALTERNATIVE 11-ELECTRODE NETWORK
%
% Purpose
% -------
% Determine the final HC/PD cohort available for the alternative-network
% robustness analysis BEFORE calculating any connectivity results.
%
% FROZEN alternative network:
%
%   FL = F3
%   FM = AFz
%   FR = F4
%   CL = C5
%   CR = C6
%   PL = P5
%   PM = POz
%   PR = P6
%   TL = TP9
%   TR = TP10
%   O  = Oz
%
% Rules:
%   - All 11 electrodes must be present.
%   - No interpolation.
%   - No substitute electrode if one is missing.
%   - This script DOES NOT calculate connectivity.
%% =========================================================================

clear;
clc;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();

%% =========================================================================
% 1. PATHS
%% =========================================================================

datasetRoot = ...
    cfg.datasetRoot;

icaRoot = fullfile( ...
    datasetRoot, ...
    'PAPER3_FULL130_ICA');

statsInputFile = fullfile( ...
    datasetRoot, ...
    'PAPER3_FINAL_CONNECTIVITY', ...
    'Paper3_CONNECTIVITY_STATS_INPUT.mat');

outRoot = fullfile( ...
    datasetRoot, ...
    'PAPER3_ALTERNATIVE_NETWORK');

if ~exist(outRoot,'dir')
    mkdir(outRoot);
end

%% =========================================================================
% 2. LOAD FINAL WORKING COHORT
%% =========================================================================

if ~exist(statsInputFile,'file')
    error('Stats input file not found:\n%s',statsInputFile);
end

S = load( ...
    statsInputFile, ...
    'subjects', ...
    'groups');

subjects = string(S.subjects(:));
groups   = string(S.groups(:));

N = numel(subjects);

if N ~= 130
    error('Expected final working cohort N=130; found N=%d.',N);
end

fprintf('\n============================================================\n');
fprintf('FINAL ALTERNATIVE NETWORK COHORT CHECK\n');
fprintf('============================================================\n');

fprintf('Working cohort N = %d\n',N);
fprintf('HC = %d\n',sum(groups=="HC"));
fprintf('PD = %d\n',sum(groups=="PD"));

%% =========================================================================
% 3. FROZEN ALTERNATIVE NETWORK
%% =========================================================================

altNodeNames = [ ...
    "FL"
    "FM"
    "FR"
    "CL"
    "CR"
    "PL"
    "PM"
    "PR"
    "TL"
    "TR"
    "O"];

altElectrodes = [ ...
    "F3"
    "AFz"
    "F4"
    "C5"
    "C6"
    "P5"
    "POz"
    "P6"
    "TP9"
    "TP10"
    "Oz"];

if numel(altNodeNames) ~= 11 || ...
   numel(altElectrodes) ~= 11

    error('Alternative network must contain exactly 11 nodes/electrodes.');

end

fprintf('\nFrozen alternative montage:\n');

for k = 1:11

    fprintf('%-3s = %s\n', ...
        altNodeNames(k), ...
        altElectrodes(k));

end

%% =========================================================================
% 4. CHECK SUBJECT-LEVEL ELECTRODE AVAILABILITY
%% =========================================================================

availableMatrix = ...
    false(N,11);

completeAltNetwork = ...
    false(N,1);

nAvailable = ...
    zeros(N,1);

missingElectrodes = ...
    strings(N,1);

for s = 1:N

    subj = subjects(s);

    subjDir = ...
        fullfile( ...
            icaRoot, ...
            char(subj));

    commonICAFile = ...
        fullfile( ...
            subjDir, ...
            sprintf( ...
                '%s_commonICA.mat', ...
                subj));

    if ~exist(commonICAFile,'file')

        warning( ...
            'Missing commonICA file for %s.', ...
            subj);

        missingElectrodes(s) = "FILE_MISSING";

        continue;

    end

    C = load( ...
        commonICAFile, ...
        'goodLabels');

    if ~isfield(C,'goodLabels')

        warning( ...
            '%s lacks goodLabels.', ...
            subj);

        missingElectrodes(s) = "GOODLABELS_MISSING";

        continue;

    end

    goodLabels = ...
        string(C.goodLabels(:));

    % --------------------------------------------------------------
    % Check each required frozen representative electrode.
    % --------------------------------------------------------------

    for e = 1:11

        availableMatrix(s,e) = ...
            any( ...
                strcmpi( ...
                    goodLabels, ...
                    altElectrodes(e)));

    end

    nAvailable(s) = ...
        sum(availableMatrix(s,:));

    completeAltNetwork(s) = ...
        all(availableMatrix(s,:));

    missingNow = ...
        altElectrodes( ...
            ~availableMatrix(s,:));

    if isempty(missingNow)

        missingElectrodes(s) = "";

    else

        missingElectrodes(s) = ...
            strjoin( ...
                missingNow, ...
                ",");

    end

end

%% =========================================================================
% 5. FINAL COHORT COUNTS
%% =========================================================================

nComplete = ...
    sum(completeAltNetwork);

nHC_complete = ...
    sum( ...
        completeAltNetwork & ...
        groups=="HC");

nPD_complete = ...
    sum( ...
        completeAltNetwork & ...
        groups=="PD");

nIncomplete = ...
    sum(~completeAltNetwork);

nHC_incomplete = ...
    sum( ...
        ~completeAltNetwork & ...
        groups=="HC");

nPD_incomplete = ...
    sum( ...
        ~completeAltNetwork & ...
        groups=="PD");

fprintf('\n============================================================\n');
fprintf('FINAL COMPLETE ALTERNATIVE-NETWORK COHORT\n');
fprintf('============================================================\n');

fprintf('Total complete = %d / %d\n', ...
    nComplete,N);

fprintf('HC complete    = %d / %d\n', ...
    nHC_complete, ...
    sum(groups=="HC"));

fprintf('PD complete    = %d / %d\n', ...
    nPD_complete, ...
    sum(groups=="PD"));

fprintf('\nIncomplete total = %d\n', ...
    nIncomplete);

fprintf('HC incomplete    = %d\n', ...
    nHC_incomplete);

fprintf('PD incomplete    = %d\n', ...
    nPD_incomplete);

%% =========================================================================
% 6. AVAILABILITY FOR EACH FROZEN ELECTRODE
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('FROZEN ELECTRODE AVAILABILITY\n');
fprintf('============================================================\n');

for e = 1:11

    nAll = ...
        sum(availableMatrix(:,e));

    nHC = ...
        sum( ...
            availableMatrix(:,e) & ...
            groups=="HC");

    nPD = ...
        sum( ...
            availableMatrix(:,e) & ...
            groups=="PD");

    fprintf( ...
        '%-3s %-4s : %3d/%3d total | HC %2d/%2d | PD %3d/%3d\n', ...
        altNodeNames(e), ...
        altElectrodes(e), ...
        nAll, ...
        N, ...
        nHC, ...
        sum(groups=="HC"), ...
        nPD, ...
        sum(groups=="PD"));

end

%% =========================================================================
% 7. LIST SUBJECTS EXCLUDED FROM ALTERNATIVE COMPLETE NETWORK
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('SUBJECTS MISSING >=1 FROZEN ELECTRODE\n');
fprintf('============================================================\n');

idxIncomplete = ...
    find(~completeAltNetwork);

if isempty(idxIncomplete)

    fprintf('None. All participants retain all 11 electrodes.\n');

else

    for k = 1:numel(idxIncomplete)

        s = idxIncomplete(k);

        fprintf( ...
            '%-8s %-2s | Available %2d/11 | Missing: %s\n', ...
            subjects(s), ...
            groups(s), ...
            nAvailable(s), ...
            missingElectrodes(s));

    end

end

%% =========================================================================
% 8. COMPARE WITH ORIGINAL PRIMARY COMPLETE-NETWORK COHORT
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('COMPARISON WITH ORIGINAL PRIMARY COHORT\n');
fprintf('============================================================\n');

if isfield(S,'completeNetworkMask')

    originalMask = ...
        logical(S.completeNetworkMask(:));

else

    T = load( ...
        statsInputFile, ...
        'completeNetworkMask');

    originalMask = ...
        logical(T.completeNetworkMask(:));

end

nOriginal = ...
    sum(originalMask);

nOriginalHC = ...
    sum(originalMask & groups=="HC");

nOriginalPD = ...
    sum(originalMask & groups=="PD");

fprintf('Original primary network:\n');
fprintf('N  = %d\n',nOriginal);
fprintf('HC = %d\n',nOriginalHC);
fprintf('PD = %d\n',nOriginalPD);

fprintf('\nFrozen alternative network:\n');
fprintf('N  = %d\n',nComplete);
fprintf('HC = %d\n',nHC_complete);
fprintf('PD = %d\n',nPD_complete);

fprintf('\nDifference alternative - original:\n');
fprintf('Total = %+d\n',nComplete-nOriginal);
fprintf('HC    = %+d\n',nHC_complete-nOriginalHC);
fprintf('PD    = %+d\n',nPD_complete-nOriginalPD);

% Subjects included in alternative network but not primary network.
altOnly = ...
    completeAltNetwork & ...
    ~originalMask;

% Subjects in primary network but not alternative.
primaryOnly = ...
    originalMask & ...
    ~completeAltNetwork;

fprintf('\nAlternative-only subjects = %d\n', ...
    sum(altOnly));

if any(altOnly)

    disp(table( ...
        subjects(altOnly), ...
        groups(altOnly), ...
        'VariableNames',{ ...
            'Subject', ...
            'Group'}));

end

fprintf('Primary-only subjects = %d\n', ...
    sum(primaryOnly));

if any(primaryOnly)

    disp(table( ...
        subjects(primaryOnly), ...
        groups(primaryOnly), ...
        missingElectrodes(primaryOnly), ...
        'VariableNames',{ ...
            'Subject', ...
            'Group', ...
            'MissingAlternativeElectrode'}));

end

%% =========================================================================
% 9. SUBJECT-LEVEL TABLE
%% =========================================================================

AvailabilityTable = table( ...
    subjects, ...
    groups, ...
    completeAltNetwork, ...
    nAvailable, ...
    missingElectrodes, ...
    originalMask, ...
    'VariableNames',{ ...
        'Subject', ...
        'Group', ...
        'CompleteAlternativeNetwork', ...
        'N_Available_of_11', ...
        'MissingElectrodes', ...
        'OriginalPrimaryCompleteNetwork'});

for e = 1:11

    varName = ...
        matlab.lang.makeValidName( ...
            sprintf( ...
                'Has_%s', ...
                altElectrodes(e)));

    AvailabilityTable.(varName) = ...
        availableMatrix(:,e);

end

%% =========================================================================
% 10. SUMMARY TABLE
%% =========================================================================

SummaryTable = table( ...
    ["HC";"PD";"Total"], ...
    [sum(groups=="HC"); ...
     sum(groups=="PD"); ...
     N], ...
    [nHC_complete; ...
     nPD_complete; ...
     nComplete], ...
    [nHC_incomplete; ...
     nPD_incomplete; ...
     nIncomplete], ...
    [nOriginalHC; ...
     nOriginalPD; ...
     nOriginal], ...
    'VariableNames',{ ...
        'Group', ...
        'WorkingCohortN', ...
        'AlternativeCompleteN', ...
        'AlternativeIncompleteN', ...
        'OriginalPrimaryCompleteN'});

fprintf('\n============================================================\n');
fprintf('SUMMARY TABLE\n');
fprintf('============================================================\n');

disp(SummaryTable);

%% =========================================================================
% 11. SAVE FROZEN MAPPING
%% =========================================================================

FrozenMappingTable = table( ...
    altNodeNames, ...
    altElectrodes, ...
    'VariableNames',{ ...
        'Node', ...
        'RepresentativeElectrode'});

writetable( ...
    FrozenMappingTable, ...
    fullfile( ...
        outRoot, ...
        'FINAL_Alternative11Electrode_FrozenMapping.csv'));

%% =========================================================================
% 12. SAVE SUBJECT / COHORT RESULTS
%% =========================================================================

writetable( ...
    AvailabilityTable, ...
    fullfile( ...
        outRoot, ...
        'FINAL_Alternative11Electrode_subject_availability.csv'));

writetable( ...
    SummaryTable, ...
    fullfile( ...
        outRoot, ...
        'FINAL_Alternative11Electrode_cohort_summary.csv'));

save( ...
    fullfile( ...
        outRoot, ...
        'FINAL_Alternative11Electrode_cohort_check.mat'), ...
    'subjects', ...
    'groups', ...
    'altNodeNames', ...
    'altElectrodes', ...
    'availableMatrix', ...
    'completeAltNetwork', ...
    'nAvailable', ...
    'missingElectrodes', ...
    'originalMask', ...
    'AvailabilityTable', ...
    'SummaryTable', ...
    'FrozenMappingTable');

fprintf('\n============================================================\n');
fprintf('FINAL ALTERNATIVE COHORT CHECK COMPLETE\n');
fprintf('============================================================\n');

fprintf('\nOutputs saved in:\n%s\n',outRoot);