function maxExtent = joint_max_component_extent( ...
    vVec, ...
    nEdges, ...
    nBands, ...
    threshold, ...
    edgeIndex1, ...
    edgeIndex2, ...
    nNodes)

    V = ...
        reshape( ...
            vVec, ...
            nEdges, ...
            nBands);

    maxExtent = 0;

