% SELF-TEST: v STATISTIC MUST REDUCE TO WELCH t
%% =========================================================================

function run_v_statistic_selftest()

    group = [ ...
        zeros(5,1)
        ones(8,1)];

    yHC = [ ...
        1.0
        2.0
        2.3
        3.1
        4.7];

    yPD = [ ...
        2.4
        2.9
        4.0
        5.2
        5.7
        6.1
        7.8
        9.0];

    y = ...
        [yHC;yPD];

    M = [ ...
        ones(numel(y),1), ...
        group];

    C = [0;1];

    Mpinv = ...
        pinv(M);

    H = ...
        M*Mpinv;

    Rdiag = ...
        diag( ...
            eye(numel(y))-H);

    g0 = ...
        group==0;

    g1 = ...
        group==1;

    sumR0 = ...
        sum(Rdiag(g0));

    sumR1 = ...
        sum(Rdiag(g1));

    A0 = ...
        M(g0,:)'*M(g0,:);

    A1 = ...
        M(g1,:)'*M(g1,:);

    [v,~] = ...
        compute_signed_v_all( ...
            y, ...
            M, ...
            Mpinv, ...
            C, ...
            2, ...
            g0, ...
            g1, ...
            sumR0, ...
            sumR1, ...
            A0, ...
            A1);

    welch = ...
        (mean(yPD)-mean(yHC)) / ...
        sqrt( ...
            var(yPD,0)/numel(yPD) + ...
            var(yHC,0)/numel(yHC));

    if abs(v-welch) > 1e-10

        error( ...
            'v self-test failed: v=%.12g Welch=%.12g', ...
            v, ...
            welch);

    end

end

