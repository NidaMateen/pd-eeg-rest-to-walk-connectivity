% EMPIRICAL PERCENTILE
%% =========================================================================

function q = empirical_percentile(x,p)

    x = ...
        sort( ...
            double(x(:)));

    x = ...
        x(isfinite(x));

    if isempty(x)

        q = NaN;
        return;

    end

    p = ...
        max(0,min(1,p));

    pos = ...
        1 + ...
        (numel(x)-1)*p;

    lo = ...
        floor(pos);

    hi = ...
        ceil(pos);

    if lo==hi

        q = ...
            x(lo);

    else

        w = ...
            pos-lo;

        q = ...
            (1-w)*x(lo) + ...
            w*x(hi);

    end

end

