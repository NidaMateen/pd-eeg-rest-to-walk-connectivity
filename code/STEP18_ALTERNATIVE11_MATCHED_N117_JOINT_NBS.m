%% =========================================================================
% PAPER 3 — STEP 18
% ALTERNATIVE 11-ELECTRODE NETWORK
% MATCHED N=117 JOINT NBS ROBUSTNESS ANALYSIS
%
% PURPOSE
% -------
% Test whether the primary network-level result is robust to a different
% network construction.
%
% IMPORTANT:
%   This analysis uses EXACTLY the same N=117 participants as the primary
%   regional-network NBS:
%
%       N = 117 = 22 HC + 95 PD
%
%   Only the network representation changes:
%
%   PRIMARY:
%       regional median aggregation across multiple sensor pairs
%
%   ALTERNATIVE:
%       one fixed representative electrode per node
%
% Frozen alternative montage:
%
%   FL = F3
%   FM = AFz
%   FR = F4
%   CL = C5
%   CR = C6
%   PL = P5
%   PM = POz
%   PR = P6
%   TL = TP9
%   TR = TP10
%   O  = Oz
%
% PRIMARY-MATCHED NBS SETTINGS
% ----------------------------
% Outcome:
%   Delta db-wPLI = Walk - Rest
%
% Full model:
%   Delta = Intercept + Group + Age_c + Sex
%
% Reduced model:
%   Delta = Intercept + Age_c + Sex
%
% Group:
%   HC = 0
%   PD = 1
%
% Sex:
%   F = 0
%   M = 1
%
% Edge statistic:
%   signed heteroscedasticity-aware rank-1 v statistic
%   HC and PD treated as separate variance groups
%
% Null:
%   Freedman-Lane reduced-model residual sign flipping
%
% Same subject-level Rademacher sign applied jointly across:
%   55 edges x 3 biological bands
%
% NBS:
%   |v| > 2.5
%   positive and negative components separately
%   component statistic = extent (# edges)
%
% Multiplicity:
%   one joint maximum null across:
%     theta+
%     theta-
%     alpha+
%     alpha-
%     beta+
%     beta-
%
% Resamples:
%   10,000
%
% Seed:
%   20260916
%
% Corrected p:
%   (1 + number(null max >= observed extent)) / (B + 1)
%
% NOTE:
%   This is a post-hoc network-construction robustness analysis.
%   It does NOT replace the original confirmatory primary NBS.
%% =========================================================================

clear;
clc;
close all;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();

%% =========================================================================
% 1. FIXED SETTINGS
%% =========================================================================

N_EXPECTED       = 117;
N_HC_EXPECTED    = 22;
N_PD_EXPECTED    = 95;

N_NODES          = 11;
N_EDGES          = 55;
N_BANDS          = 3;

N_RESAMPLES      = 10000;
RNG_SEED         = 20260916;

NBS_THRESHOLD    = 2.5;
ALPHA_FWER       = 0.05;

BIO_BANDS_EXPECTED = [ ...
    "theta"
    "alpha"
    "beta"];

% Keep same computational settings as original primary script.
USE_PARALLEL = true;
N_WORKERS = 2;

PERMUTATION_CHUNK_SIZE = 500;

%% =========================================================================
% 2. PATHS
%% =========================================================================

datasetRoot = ...
    cfg.datasetRoot;

altRoot = fullfile( ...
    datasetRoot, ...
    'PAPER3_ALTERNATIVE_NETWORK');

altFile = fullfile( ...
    altRoot, ...
    'Paper3_ALTERNATIVE11_MATCHED_N117.mat');

statsInputFile = fullfile( ...
    datasetRoot, ...
    'PAPER3_FINAL_CONNECTIVITY', ...
    'Paper3_CONNECTIVITY_STATS_INPUT.mat');

participantsFile = fullfile( ...
    datasetRoot, ...
    'participants.tsv');

outRoot = fullfile( ...
    altRoot, ...
    'STEP18_ALT11_MATCHED_N117_NBS');

if ~exist(outRoot,'dir')
    mkdir(outRoot);
end

if ~exist(altFile,'file')
    error('Alternative matched file not found:\n%s',altFile);
end

if ~exist(statsInputFile,'file')
    error('Primary stats input file not found:\n%s',statsInputFile);
end

if ~exist(participantsFile,'file')
    error('participants.tsv not found:\n%s',participantsFile);
end

%% =========================================================================
% 3. LOAD FROZEN ALTERNATIVE NETWORK
%% =========================================================================

A = load(altFile);

requiredFields = { ...
    'subjectsMatched', ...
    'groupsMatched', ...
    'deltaMatched', ...
    'altNodeNames', ...
    'altElectrodes', ...
    'bandNamesReference', ...
    'bioBandIdx', ...
    'EdgeTable'};

for k = 1:numel(requiredFields)

    if ~isfield(A,requiredFields{k})

        error( ...
            'Alternative file missing required field: %s', ...
            requiredFields{k});

    end

end

subjects = string(A.subjectsMatched(:));
groups   = string(A.groupsMatched(:));

deltaAll = double(A.deltaMatched);

altNodeNames   = string(A.altNodeNames(:));
altElectrodes  = string(A.altElectrodes(:));

bandNamesReference = ...
    string(A.bandNamesReference(:));

bioBandIdx = ...
    double(A.bioBandIdx(:))';

EdgeTable = ...
    A.EdgeTable;

%% =========================================================================
% 4. VALIDATE MATCHED COHORT
%% =========================================================================

N = numel(subjects);

if N ~= N_EXPECTED
    error('Expected N=117; found N=%d.',N);
end

if sum(groups=="HC") ~= N_HC_EXPECTED
    error('Expected 22 HC.');
end

if sum(groups=="PD") ~= N_PD_EXPECTED
    error('Expected 95 PD.');
end

if size(deltaAll,1) ~= N_EXPECTED
    error('deltaMatched first dimension must equal 117.');
end

if size(deltaAll,2) ~= N_EDGES
    error('Expected 55 alternative-network edges.');
end

if numel(bioBandIdx) ~= 3
    error('Expected exactly three biological bands.');
end

bioBandNames = ...
    lower(bandNamesReference(bioBandIdx));

if ~isequal(bioBandNames,BIO_BANDS_EXPECTED)

    fprintf('\nDetected biological bands:\n');
    disp(bioBandNames);

    error('Biological band order differs from theta/alpha/beta.');

end

%% =========================================================================
% 5. VERIFY SUBJECTS ARE EXACTLY THE ORIGINAL PRIMARY N=117
%% =========================================================================

P0 = load( ...
    statsInputFile, ...
    'subjects', ...
    'groups', ...
    'completeNetworkMask');

primarySubjectsAll = ...
    string(P0.subjects(:));

primaryGroupsAll = ...
    string(P0.groups(:));

primaryMask = ...
    logical(P0.completeNetworkMask(:));

primarySubjects = ...
    primarySubjectsAll(primaryMask);

primaryGroups = ...
    primaryGroupsAll(primaryMask);

fprintf('\n============================================================\n');
fprintf('MATCHED-COHORT IDENTITY CHECK\n');
fprintf('============================================================\n');

fprintf('Primary NBS cohort N     = %d\n', ...
    numel(primarySubjects));

fprintf('Alternative matched N    = %d\n', ...
    numel(subjects));

if ~isequal(subjects,primarySubjects)

    error([ ...
        'Alternative matched subject order differs from original ' ...
        'primary NBS cohort.']);

end

if ~isequal(groups,primaryGroups)

    error('Group order differs from original primary NBS cohort.');

end

fprintf('Subject IDs identical    = 1\n');
fprintf('Subject order identical  = 1\n');
fprintf('Group order identical    = 1\n');

fprintf('\nPASS: network representation is the only changed element.\n');

%% =========================================================================
% 6. BIOLOGICAL-BAND DATA
%% =========================================================================

deltaNBS = ...
    deltaAll(:,:,bioBandIdx);

if ~isequal(size(deltaNBS), ...
        [N_EXPECTED N_EDGES N_BANDS])

    error('Expected biological data size 117 x 55 x 3.');

end

if any(~isfinite(deltaNBS),'all')

    error('Alternative NBS data contain NaN/Inf.');

end

% MATLAB reshape ordering:
%
% columns 1:55     = theta edges 1:55
% columns 56:110   = alpha edges 1:55
% columns 111:165  = beta edges 1:55

Y = ...
    reshape( ...
        deltaNBS, ...
        N, ...
        N_EDGES*N_BANDS);

%% =========================================================================
% 7. EDGE / NODE METADATA
%% =========================================================================

edgeIndex1 = ...
    double(EdgeTable.NodeIndex1(:));

edgeIndex2 = ...
    double(EdgeTable.NodeIndex2(:));

edgeNames = ...
    string(EdgeTable.EdgeName(:));

if ismember( ...
        'ElectrodePair', ...
        EdgeTable.Properties.VariableNames)

    edgeElectrodePairs = ...
        string(EdgeTable.ElectrodePair(:));

else

    edgeElectrodePairs = ...
        strings(N_EDGES,1);

    for e = 1:N_EDGES

        edgeElectrodePairs(e) = ...
            altElectrodes(edgeIndex1(e)) + "-" + ...
            altElectrodes(edgeIndex2(e));

    end

end

if numel(edgeIndex1) ~= N_EDGES || ...
   numel(edgeIndex2) ~= N_EDGES

    error('Edge metadata must contain exactly 55 edges.');

end

%% =========================================================================
% 8. LOAD AGE / SEX
%% =========================================================================

P = readtable( ...
    participantsFile, ...
    'FileType','text', ...
    'Delimiter','\t', ...
    'TextType','string');

needed = [ ...
    "participant_id"
    "group"
    "age"
    "sex"];

for k = 1:numel(needed)

    if ~ismember( ...
            needed(k), ...
            string(P.Properties.VariableNames))

        error( ...
            'participants.tsv missing column: %s', ...
            needed(k));

    end

end

[tf,loc] = ...
    ismember( ...
        subjects, ...
        string(P.participant_id));

if ~all(tf)

    fprintf('\nSubjects missing from participants.tsv:\n');
    disp(subjects(~tf));

    error('Participant alignment failed.');

end

participantGroups = ...
    string(P.group(loc));

if ~isequal(participantGroups,groups)

    error('Group mismatch with participants.tsv.');

end

age = ...
    column_to_double(P.age(loc));

sexRaw = ...
    upper( ...
        strtrim( ...
            string(P.sex(loc))));

if any(~isfinite(age))
    error('Age contains NaN/Inf.');
end

if any(~ismember(sexRaw,["F","M"]))
    error('Unexpected sex coding.');
end

%% =========================================================================
% 9. DESIGN MATRICES
%% =========================================================================

Group = ...
    double(groups=="PD");

Sex = ...
    double(sexRaw=="M");

Age_c = ...
    age - mean(age);

% Full model:
%
% [Intercept Group Age_c Sex]

M = [ ...
    ones(N,1), ...
    Group, ...
    Age_c, ...
    Sex];

% Reduced model:
%
% [Intercept Age_c Sex]

Z = [ ...
    ones(N,1), ...
    Age_c, ...
    Sex];

if rank(M) ~= size(M,2)
    error('Full model is rank deficient.');
end

if rank(Z) ~= size(Z,2)
    error('Reduced model is rank deficient.');
end

groupColumn = 2;

C = [ ...
    0
    1
    0
    0];

fprintf('\n============================================================\n');
fprintf('ALTERNATIVE NBS DESIGN\n');
fprintf('============================================================\n');

fprintf('N             = %d = %d HC + %d PD\n', ...
    N, ...
    sum(Group==0), ...
    sum(Group==1));

fprintf('Age mean      = %.6f\n',mean(age));

fprintf('Full model    = Intercept + Group + Age_c + Sex\n');
fprintf('Reduced model = Intercept + Age_c + Sex\n');

fprintf('Threshold     = |v| > %.2f\n',NBS_THRESHOLD);
fprintf('Resamples     = %d\n',N_RESAMPLES);
fprintf('Seed          = %d\n',RNG_SEED);

%% =========================================================================
% 10. VARIANCE GROUPS / PRECOMPUTATIONS
%% =========================================================================

vgHC = ...
    Group==0;

vgPD = ...
    Group==1;

Mpinv = ...
    pinv(M);

Hfull = ...
    M*Mpinv;

Rfull = ...
    eye(N)-Hfull;

Rdiag = ...
    diag(Rfull);

sumR_HC = ...
    sum(Rdiag(vgHC));

sumR_PD = ...
    sum(Rdiag(vgPD));

if sumR_HC <= 0 || ...
   sumR_PD <= 0

    error('Invalid variance-group residual degrees of freedom.');

end

A_HC = ...
    M(vgHC,:)' * M(vgHC,:);

A_PD = ...
    M(vgPD,:)' * M(vgPD,:);

% Reduced model quantities.
Zpinv = ...
    pinv(Z);

B_reduced = ...
    Zpinv*Y;

FittedReduced = ...
    Z*B_reduced;

ResidualReduced = ...
    Y-FittedReduced;

clear B_reduced;

%% =========================================================================
% 11. IMPLEMENTATION SELF-TESTS
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('IMPLEMENTATION SELF-TESTS\n');
fprintf('============================================================\n');

run_v_statistic_selftest();
fprintf('Signed-v / Welch equivalence self-test: PASS\n');

run_component_selftest();
fprintf('NBS component-finding self-test       : PASS\n');

%% =========================================================================
% 12. OBSERVED EDGE STATISTICS
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('COMPUTING OBSERVED ALTERNATIVE-NETWORK STATISTICS\n');
fprintf('============================================================\n');

[vObservedVec,betaGroupVec] = ...
    compute_signed_v_all( ...
        Y, ...
        M, ...
        Mpinv, ...
        C, ...
        groupColumn, ...
        vgHC, ...
        vgPD, ...
        sumR_HC, ...
        sumR_PD, ...
        A_HC, ...
        A_PD);

if any(~isfinite(vObservedVec))
    error('Observed v statistics contain NaN/Inf.');
end

vObserved = ...
    reshape( ...
        vObservedVec, ...
        N_EDGES, ...
        N_BANDS);

betaGroup = ...
    reshape( ...
        betaGroupVec, ...
        N_EDGES, ...
        N_BANDS);

%% =========================================================================
% 13. SAVE OBSERVED EDGE TABLE
%% =========================================================================

nRows = ...
    N_EDGES*N_BANDS;

BandCol = ...
    strings(nRows,1);

EdgeIndexCol = ...
    zeros(nRows,1);

Node1Col = ...
    strings(nRows,1);

Node2Col = ...
    strings(nRows,1);

ElectrodePairCol = ...
    strings(nRows,1);

BetaCol = ...
    nan(nRows,1);

VCol = ...
    nan(nRows,1);

PositiveThresholdCol = ...
    false(nRows,1);

NegativeThresholdCol = ...
    false(nRows,1);

row = 0;

for b = 1:N_BANDS

    for e = 1:N_EDGES

        row = row+1;

        BandCol(row) = ...
            BIO_BANDS_EXPECTED(b);

        EdgeIndexCol(row) = ...
            e;

        Node1Col(row) = ...
            altNodeNames(edgeIndex1(e));

        Node2Col(row) = ...
            altNodeNames(edgeIndex2(e));

        ElectrodePairCol(row) = ...
            edgeElectrodePairs(e);

        BetaCol(row) = ...
            betaGroup(e,b);

        VCol(row) = ...
            vObserved(e,b);

        PositiveThresholdCol(row) = ...
            vObserved(e,b) > NBS_THRESHOLD;

        NegativeThresholdCol(row) = ...
            vObserved(e,b) < -NBS_THRESHOLD;

    end

end

ObservedEdgeTable = table( ...
    BandCol, ...
    EdgeIndexCol, ...
    Node1Col, ...
    Node2Col, ...
    ElectrodePairCol, ...
    BetaCol, ...
    VCol, ...
    PositiveThresholdCol, ...
    NegativeThresholdCol, ...
    'VariableNames',{ ...
        'Band', ...
        'EdgeIndex', ...
        'Node1', ...
        'Node2', ...
        'ElectrodePair', ...
        'Beta_PDminusHC_adjusted', ...
        'VStatistic', ...
        'AbovePositiveThreshold', ...
        'BelowNegativeThreshold'});

writetable( ...
    ObservedEdgeTable, ...
    fullfile( ...
        outRoot, ...
        'Paper3_ALT11_N117_observed_edge_statistics.csv'));

%% =========================================================================
% 14. OBSERVED NBS COMPONENTS
%% =========================================================================

observedComponents = ...
    cell(N_BANDS,2);

% column 1 = positive
% column 2 = negative

for b = 1:N_BANDS

    observedComponents{b,1} = ...
        find_nbs_components( ...
            vObserved(:,b), ...
            +1, ...
            NBS_THRESHOLD, ...
            edgeIndex1, ...
            edgeIndex2, ...
            N_NODES);

    observedComponents{b,2} = ...
        find_nbs_components( ...
            vObserved(:,b), ...
            -1, ...
            NBS_THRESHOLD, ...
            edgeIndex1, ...
            edgeIndex2, ...
            N_NODES);

end

fprintf('\n============================================================\n');
fprintf('OBSERVED SUPRATHRESHOLD COMPONENTS BEFORE CORRECTION\n');
fprintf('============================================================\n');

for b = 1:N_BANDS

    posExt = ...
        component_extents( ...
            observedComponents{b,1});

    negExt = ...
        component_extents( ...
            observedComponents{b,2});

    fprintf('%-5s + : %s\n', ...
        BIO_BANDS_EXPECTED(b), ...
        mat2str(posExt));

    fprintf('%-5s - : %s\n', ...
        BIO_BANDS_EXPECTED(b), ...
        mat2str(negExt));

end

%% =========================================================================
% 15. GENERATE FIXED RADEMACHER SIGN MATRIX
%% =========================================================================

% Since N=117 and subject order are identical to the primary NBS,
% this produces the same subject-level sign matrix used by the original
% analysis when the same seed is used.

rng(RNG_SEED,'twister');

signMatrix = ...
    int8( ...
        ones(N_RESAMPLES,N));

flipMask = ...
    rand(N_RESAMPLES,N) < 0.5;

signMatrix(flipMask) = ...
    -1;

clear flipMask;

%% =========================================================================
% 16. CHECKPOINT SETUP
%% =========================================================================

checkpointFile = fullfile( ...
    outRoot, ...
    'Paper3_ALT11_N117_NBS_checkpoint.mat');

nullMaxExtent = ...
    nan(N_RESAMPLES,1);

completedResamples = ...
    0;

if exist(checkpointFile,'file')

    Q = load(checkpointFile);

    requiredCheckpoint = { ...
        'nullMaxExtent', ...
        'completedResamples', ...
        'N_RESAMPLES', ...
        'RNG_SEED', ...
        'NBS_THRESHOLD', ...
        'subjects', ...
        'groups', ...
        'age', ...
        'Sex', ...
        'vObserved'};

    checkpointOK = true;

    for q = 1:numel(requiredCheckpoint)

        checkpointOK = ...
            checkpointOK && ...
            isfield(Q,requiredCheckpoint{q});

    end

    if checkpointOK

        checkpointOK = ...
            Q.N_RESAMPLES == N_RESAMPLES && ...
            Q.RNG_SEED == RNG_SEED && ...
            Q.NBS_THRESHOLD == NBS_THRESHOLD && ...
            isequal(string(Q.subjects(:)),subjects) && ...
            isequal(string(Q.groups(:)),groups) && ...
            isequal(double(Q.age(:)),age) && ...
            isequal(double(Q.Sex(:)),Sex) && ...
            isequaln(double(Q.vObserved),vObserved);

    end

    if ~checkpointOK

        error([ ...
            'Existing STEP18 checkpoint does not match the current ' ...
            'alternative-network analysis.']);

    end

    nullMaxExtent = ...
        double(Q.nullMaxExtent(:));

    completedResamples = ...
        double(Q.completedResamples);

    fprintf('\nResuming from checkpoint: %d/%d complete.\n', ...
        completedResamples, ...
        N_RESAMPLES);

    clear Q;

end

%% =========================================================================
% 17. PARALLEL POOL
%% =========================================================================

if USE_PARALLEL && ...
   license('test','Distrib_Computing_Toolbox')

    pool = ...
        gcp('nocreate');

    if isempty(pool)

        pool = ...
            parpool('local',N_WORKERS);

    elseif pool.NumWorkers ~= N_WORKERS

        delete(pool);

        pool = ...
            parpool('local',N_WORKERS);

    end

    useParallelNow = true;

    fprintf('\nNBS resampling will use %d workers.\n', ...
        pool.NumWorkers);

else

    useParallelNow = false;

    fprintf('\nNBS resampling will run sequentially.\n');

end

%% =========================================================================
% 18. 10,000 FREEDMAN-LANE SIGN-FLIP RESAMPLES
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('ALTERNATIVE-NETWORK JOINT NBS RESAMPLING\n');
fprintf('============================================================\n');

fprintf('Subjects      = %d\n',N);
fprintf('Edges         = %d\n',N_EDGES);
fprintf('Bands         = %d\n',N_BANDS);
fprintf('Resamples     = %d\n',N_RESAMPLES);
fprintf('Seed          = %d\n',RNG_SEED);
fprintf('Threshold     = |v| > %.2f\n',NBS_THRESHOLD);
fprintf('Statistic     = component edge extent\n');
fprintf('Joint family  = theta+/-, alpha+/-, beta+/-\n');

totalTimer = tic;

startResample = ...
    completedResamples+1;

for chunkStart = ...
        startResample: ...
        PERMUTATION_CHUNK_SIZE: ...
        N_RESAMPLES

    chunkEnd = min( ...
        chunkStart + ...
        PERMUTATION_CHUNK_SIZE - 1, ...
        N_RESAMPLES);

    idxChunk = ...
        chunkStart:chunkEnd;

    chunkMax = ...
        zeros(numel(idxChunk),1);

    chunkTimer = tic;

    if useParallelNow

        parfor jj = 1:numel(idxChunk)

            resampleIndex = ...
                idxChunk(jj);

            signs = ...
                double( ...
                    signMatrix(resampleIndex,:))';

            % Freedman-Lane null data.
            Ystar = ...
                FittedReduced + ...
                ResidualReduced .* signs;

            vStarVec = ...
                compute_signed_v_all_only( ...
                    Ystar, ...
                    M, ...
                    Mpinv, ...
                    C, ...
                    groupColumn, ...
                    vgHC, ...
                    vgPD, ...
                    sumR_HC, ...
                    sumR_PD, ...
                    A_HC, ...
                    A_PD);

            chunkMax(jj) = ...
                joint_max_component_extent( ...
                    vStarVec, ...
                    N_EDGES, ...
                    N_BANDS, ...
                    NBS_THRESHOLD, ...
                    edgeIndex1, ...
                    edgeIndex2, ...
                    N_NODES);

        end

    else

        for jj = 1:numel(idxChunk)

            resampleIndex = ...
                idxChunk(jj);

            signs = ...
                double( ...
                    signMatrix(resampleIndex,:))';

            Ystar = ...
                FittedReduced + ...
                ResidualReduced .* signs;

            vStarVec = ...
                compute_signed_v_all_only( ...
                    Ystar, ...
                    M, ...
                    Mpinv, ...
                    C, ...
                    groupColumn, ...
                    vgHC, ...
                    vgPD, ...
                    sumR_HC, ...
                    sumR_PD, ...
                    A_HC, ...
                    A_PD);

            chunkMax(jj) = ...
                joint_max_component_extent( ...
                    vStarVec, ...
                    N_EDGES, ...
                    N_BANDS, ...
                    NBS_THRESHOLD, ...
                    edgeIndex1, ...
                    edgeIndex2, ...
                    N_NODES);

        end

    end

    nullMaxExtent(idxChunk) = ...
        chunkMax;

    completedResamples = ...
        chunkEnd;

    %% ---------------------------------------------------------------------
    % Crash-safe checkpoint.
    %% ---------------------------------------------------------------------

    CP = struct();

    CP.nullMaxExtent = ...
        nullMaxExtent;

    CP.completedResamples = ...
        completedResamples;

    CP.N_RESAMPLES = ...
        N_RESAMPLES;

    CP.RNG_SEED = ...
        RNG_SEED;

    CP.NBS_THRESHOLD = ...
        NBS_THRESHOLD;

    CP.subjects = ...
        subjects;

    CP.groups = ...
        groups;

    CP.age = ...
        age;

    CP.Sex = ...
        Sex;

    CP.vObserved = ...
        vObserved;

    atomic_save_struct( ...
        checkpointFile, ...
        CP);

    clear CP;

    fprintf( ...
        'Completed %5d / %5d | chunk %.2f min | total %.2f h\n', ...
        completedResamples, ...
        N_RESAMPLES, ...
        toc(chunkTimer)/60, ...
        toc(totalTimer)/3600);

end

if any(~isfinite(nullMaxExtent))

    error('Null maximum distribution is incomplete.');

end

%% =========================================================================
% 19. JOINT FWER COMPONENT P VALUES
%% =========================================================================

componentRows = {};

for b = 1:N_BANDS

    for d = 1:2

        comps = ...
            observedComponents{b,d};

        if d==1

            directionName = ...
                "Positive_PD_gt_HC_change";

        else

            directionName = ...
                "Negative_PD_lt_HC_change";

        end

        for cidx = 1:numel(comps)

            extent = ...
                comps(cidx).extent;

            pFWER = ...
                ( ...
                1 + ...
                sum(nullMaxExtent >= extent) ...
                ) / ...
                (N_RESAMPLES+1);

            eIdx = ...
                comps(cidx).edgeIdx(:);

            nIdx = ...
