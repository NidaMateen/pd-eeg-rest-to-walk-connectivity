%% ========================================================================
% FIGURE 4B — FINAL
% Theta vs 30-45 Hz artifact-control band
%
% Paper 3: PD EEG Rest-to-Walking Network Reconfiguration
%
% Outcome:
%   Adjusted PD-HC beta for Δ db-wPLI = Walk - Rest
%
% Comparisons:
%   1) Theta, 32-edge NBS component
%   2) 30-45 Hz control, same 32 edges
%   3) Theta, whole 55-edge network
%   4) 30-45 Hz control, whole 55-edge network
%
% Frozen results:
%
% Theta 32-edge component
%   beta = -0.045949
%   95% CI [-0.069387, -0.022511]
%   p = 0.000173
%
% High band, same 32 edges
%   beta =  0.000997
%   95% CI [-0.004125, 0.006119]
%   p = 0.70043
%
% Theta whole 55-edge network
%   beta = -0.042697
%   95% CI [-0.066857, -0.018536]
%   p = 0.000664
%
% High band whole 55-edge network
%   beta =  0.000014
%   95% CI [-0.005029, 0.005057]
%   p = 0.99561
%
% MATLAB R2023b compatible
%% ========================================================================

clear;
clc;
close all;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();

%% ========================================================================
% 1. OUTPUT DIRECTORY
%% ========================================================================

outDir = ...
    fullfile(cfg.datasetRoot,'PAPER3_PRIMARY_NBS','FIGURES');

if ~exist(outDir,'dir')
    mkdir(outDir);
end

%% ========================================================================
% 2. FROZEN RESULTS
%% ========================================================================

analysisNames = { ...
    'Theta: 32-edge component', ...
    '30-45 Hz: same 32 edges', ...
    'Theta: whole 55-edge network', ...
    '30-45 Hz: whole 55-edge network'};

beta = [ ...
    -0.045949, ...
     0.000997, ...
    -0.042697, ...
     0.000014];

CI_low = [ ...
    -0.069387, ...
    -0.004125, ...
    -0.066857, ...
    -0.005029];

CI_high = [ ...
    -0.022511, ...
     0.006119, ...
    -0.018536, ...
     0.005057];

pValue = [ ...
    0.000173, ...
    0.70043, ...
    0.000664, ...
    0.99561];

%% ========================================================================
% 3. COLORS
%% ========================================================================

thetaColor = [0.22 0.22 0.22];
controlColor = [0.55 0.55 0.55];

zeroColor = [0.72 0.72 0.72];
axisColor = [0.12 0.12 0.12];

%% ========================================================================
% 4. CREATE FIGURE
%% ========================================================================

fig = figure( ...
    'Color','w', ...
    'Units','centimeters', ...
    'Position',[3 3 13.5 8.5]);

ax = axes(fig);
hold(ax,'on');

%% ========================================================================
% 5. ROW POSITIONS
%
% Extra gap between the 32-edge and whole-network comparisons
%% ========================================================================

y = [1 2 3.5 4.5];

%% ========================================================================
% 6. ZERO REFERENCE LINE
%% ========================================================================

xline(ax,0,'--', ...
    'Color',zeroColor, ...
    'LineWidth',1.2);

%% ========================================================================
% 7. CONFIDENCE INTERVALS
%% ========================================================================

capHeight = 0.07;

for i = 1:4

    if i == 1 || i == 3
        thisColor = thetaColor;
        thisWidth = 2.1;
    else
        thisColor = controlColor;
        thisWidth = 1.8;
    end

    % Horizontal CI
    plot(ax, ...
        [CI_low(i), CI_high(i)], ...
        [y(i), y(i)], ...
        '-', ...
        'Color',thisColor, ...
        'LineWidth',thisWidth);

    % Left cap
    plot(ax, ...
        [CI_low(i), CI_low(i)], ...
        [y(i)-capHeight, y(i)+capHeight], ...
        '-', ...
        'Color',thisColor, ...
        'LineWidth',1.5);

    % Right cap
    plot(ax, ...
        [CI_high(i), CI_high(i)], ...
        [y(i)-capHeight, y(i)+capHeight], ...
        '-', ...
        'Color',thisColor, ...
        'LineWidth',1.5);
end

%% ========================================================================
% 8. POINT ESTIMATES
%% ========================================================================

% Theta estimates: filled circles
scatter(ax, ...
    beta(1), y(1), ...
    100, ...
    'o', ...
    'MarkerFaceColor',thetaColor, ...
    'MarkerEdgeColor',thetaColor, ...
    'LineWidth',1.5);

scatter(ax, ...
    beta(3), y(3), ...
    100, ...
    'o', ...
    'MarkerFaceColor',thetaColor, ...
    'MarkerEdgeColor',thetaColor, ...
    'LineWidth',1.5);

% 30-45 Hz control estimates: open circles
scatter(ax, ...
    beta(2), y(2), ...
    100, ...
    'o', ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor',controlColor, ...
    'LineWidth',1.8);

scatter(ax, ...
    beta(4), y(4), ...
    100, ...
    'o', ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor',controlColor, ...
    'LineWidth',1.8);

%% ========================================================================
% 9. OPTIONAL P-VALUE LABELS
%
% These can be removed if you want the cleanest panel.
%% ========================================================================

pTextX = 0.010;

text(ax, pTextX, y(1), ...
    'p < 0.001', ...
    'FontName','Times New Roman', ...
    'FontSize',9, ...
    'FontWeight','bold', ...
    'Color',thetaColor, ...
    'VerticalAlignment','middle');

text(ax, pTextX, y(2), ...
    'p = 0.700', ...
    'FontName','Times New Roman', ...
    'FontSize',9, ...
    'FontWeight','bold', ...
    'Color',controlColor, ...
    'VerticalAlignment','middle');

text(ax, pTextX, y(3), ...
    'p < 0.001', ...
    'FontName','Times New Roman', ...
    'FontSize',9, ...
    'FontWeight','bold', ...
    'Color',thetaColor, ...
    'VerticalAlignment','middle');

text(ax, pTextX, y(4), ...
    'p = 0.996', ...
    'FontName','Times New Roman', ...
    'FontSize',9, ...
    'FontWeight','bold', ...
    'Color',controlColor, ...
    'VerticalAlignment','middle');

%% ========================================================================
% 10. AXES
%% ========================================================================

xlim(ax,[-0.078 0.030]);
ylim(ax,[0.45 5.0]);

set(ax,'YDir','reverse');

yticks(ax,y);

yticklabels(ax,{ ...
    'Theta: 32-edge component', ...
    '30-45 Hz: same 32 edges', ...
    'Theta: whole 55-edge network', ...
    '30-45 Hz: whole 55-edge network'});

xticks(ax,[-0.07 -0.06 -0.05 -0.04 -0.03 -0.02 -0.01 0 0.01 0.02]);

xlabel(ax, ...
    'Adjusted PD-HC \beta (\Delta db-wPLI)', ...
    'FontName','Times New Roman', ...
    'FontSize',10.5, ...
    'FontWeight','bold');

%% ========================================================================
% 11. GLOBAL STYLE
%% ========================================================================

set(ax, ...
    'FontName','Times New Roman', ...
    'FontSize',9.5, ...
    'FontWeight','bold', ...
    'LineWidth',1.1, ...
    'Box','off', ...
    'TickDir','out', ...
    'TickLength',[0.018 0.018], ...
    'Layer','top');

ax.XColor = axisColor;
ax.YColor = axisColor;

%% ========================================================================
% 12. AXES POSITION
%% ========================================================================

ax.Position = [0.39 0.18 0.57 0.75];

%% ========================================================================
% 13. NO TITLE / PANEL LETTER
%
% Add "b" during final PowerPoint assembly.
%% ========================================================================

%% ========================================================================
% 14. EXPORT
%% ========================================================================

pngFile = fullfile( ...
    outDir, ...
    'Figure4B_Theta_vs_HighBand_FINAL_600dpi.png');

pdfFile = fullfile( ...
    outDir, ...
    'Figure4B_Theta_vs_HighBand_FINAL_vector.pdf');

exportgraphics( ...
    fig, ...
    pngFile, ...
    'Resolution',600, ...
    'BackgroundColor','white');

exportgraphics( ...
    fig, ...
    pdfFile, ...
    'ContentType','vector', ...
    'BackgroundColor','white');

%% ========================================================================
% 15. VERIFY VALUES
%% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE 4B — THETA VS 30-45 HZ ARTIFACT CONTROL\n');
fprintf('============================================================\n\n');

for i = 1:4

    fprintf('%s\n', analysisNames{i});
    fprintf('  beta   = %.6f\n', beta(i));
    fprintf('  95%% CI = [%.6f, %.6f]\n', CI_low(i), CI_high(i));
    fprintf('  p      = %.6f\n\n', pValue(i));

end

fprintf('Saved PNG:\n%s\n\n',pngFile);
fprintf('Saved vector PDF:\n%s\n',pdfFile);

fprintf('\n============================================================\n');