function q = ...
    empirical_percentile( ...
        x, ...
        p)


    x = ...
        sort( ...
            double(x(:)));


    if isempty(x)

        q = NaN;

        return;

    end


    p = ...
        min( ...
            max(p,0), ...
            1);


    idx = ...
        1 + ...
        (numel(x)-1)*p;


    lo = ...
        floor(idx);


    hi = ...
        ceil(idx);


    if lo==hi

        q = ...
            x(lo);

    else

        w = ...
            idx-lo;


        q = ...
            (1-w)*x(lo) + ...
            w*x(hi);

    end

end


