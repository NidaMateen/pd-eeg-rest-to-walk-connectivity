% JOINT MAXIMUM COMPONENT EXTENT
%% =========================================================================

function maxExtent = ...
    joint_max_component_extent( ...
        vVec, ...
        nEdges, ...
        nBands, ...
        threshold, ...
        edgeIndex1, ...
        edgeIndex2, ...
        nNodes)


    V = ...
        reshape( ...
            vVec, ...
            nEdges, ...
            nBands);


    maxExtent = 0;


    for b = 1:nBands

        compsPos = ...
            find_nbs_components( ...
                V(:,b), ...
                +1, ...
                threshold, ...
                edgeIndex1, ...
                edgeIndex2, ...
                nNodes);


        if ~isempty(compsPos)

            maxExtent = ...
                max( ...
                    maxExtent, ...
                    max( ...
                        [compsPos.extent]));

        end


        compsNeg = ...
            find_nbs_components( ...
                V(:,b), ...
                -1, ...
                threshold, ...
                edgeIndex1, ...
                edgeIndex2, ...
                nNodes);


        if ~isempty(compsNeg)

            maxExtent = ...
                max( ...
                    maxExtent, ...
                    max( ...
                        [compsNeg.extent]));

        end

    end

end


%% =========================================================================
% IDENTIFY CONNECTED SUPRATHRESHOLD COMPONENTS
%% =========================================================================

function comps = ...
    find_nbs_components( ...
        vEdge, ...
        direction, ...
        threshold, ...
        edgeIndex1, ...
        edgeIndex2, ...
        nNodes)


    if direction==+1

        edgeMask = ...
            vEdge > threshold;


    elseif direction==-1

        edgeMask = ...
            vEdge < -threshold;


    else

        error( ...
            'direction must be +1 or -1.');

    end


    selectedEdges = ...
        find(edgeMask);


    comps = ...
        struct( ...
            'edgeIdx',{}, ...
            'nodeIdx',{}, ...
            'extent',{});


    if isempty(selectedEdges)

        return;

    end


    A = ...
        false( ...
            nNodes, ...
            nNodes);


    for q = 1:numel(selectedEdges)

        e = ...
            selectedEdges(q);


        i = ...
            edgeIndex1(e);


        j = ...
            edgeIndex2(e);


        A(i,j) = true;

        A(j,i) = true;

    end


    activeNodes = ...
        find( ...
            any(A,2));


    visited = ...
        false( ...
            nNodes, ...
            1);


    compCount = 0;


    for seed = activeNodes(:)'


        if visited(seed)

            continue;

        end


        queue = seed;

        visited(seed) = true;

        nodesThis = ...
            zeros(0,1);


        while ~isempty(queue)

            node = ...
                queue(1);


            queue(1) = [];


            nodesThis(end+1,1) = ...
                node; %#ok<AGROW>


            nbr = ...
                find( ...
                    A(node,:));


            for nb = nbr

                if ~visited(nb)

                    visited(nb) = true;


                    queue(end+1) = ...
                        nb; %#ok<AGROW>

                end

            end

        end


        nodeMask = ...
            false( ...
                nNodes, ...
                1);


        nodeMask(nodesThis) = true;


        edgeThisMask = ...
            edgeMask & ...
            nodeMask(edgeIndex1) & ...
            nodeMask(edgeIndex2);


        edgesThis = ...
            find( ...
                edgeThisMask);


        if isempty(edgesThis)

            continue;

        end


        compCount = ...
            compCount+1;


        comps(compCount).edgeIdx = ...
            edgesThis(:);


        comps(compCount).nodeIdx = ...
            sort( ...
                nodesThis(:));


        comps(compCount).extent = ...
            numel(edgesThis);

    end

end


