function [low,high] = ...
    wilson_interval( ...
        k, ...
        n, ...
        z)


    if n<=0

        low = NaN;

        high = NaN;

        return;

    end


    phat = ...
        k/n;


    denominator = ...
        1 + ...
        z^2/n;


    center = ...
        ( ...
        phat + ...
        z^2/(2*n) ...
        ) / ...
        denominator;


    halfWidth = ...
        z * ...
        sqrt( ...
            phat*(1-phat)/n + ...
            z^2/(4*n^2)) / ...
        denominator;


    low = ...
        max( ...
            0, ...
            center-halfWidth);


    high = ...
        min( ...
            1, ...
            center+halfWidth);

end