N_EXPECTED    = 117;
N_HC_EXPECTED = 22;
N_PD_EXPECTED = 95;

N_NODES = 11;
N_EDGES = 55;
N_BANDS = 3;

BIO_BANDS_EXPECTED = [ ...
    "theta"
    "alpha"
    "beta"];


%% =========================================================================
% 3. LOAD STEP 8 CONNECTIVITY FILE
%% =========================================================================

if ~exist(statsInputFile,'file')

    error( ...
        'Statistics-input file not found:\n%s', ...
        statsInputFile);

end


S = load(statsInputFile);


requiredFields = { ...
    'subjects', ...
    'groups', ...
    'regionNames', ...
    'edgeNames', ...
    'edgeRegion1', ...
    'edgeRegion2', ...
    'edgeIndex1', ...
    'edgeIndex2', ...
    'bandNames', ...
    'deltaBio', ...
    'completeNetworkMask', ...
    'nEpochMatched'};


for k = 1:numel(requiredFields)

    if ~isfield(S,requiredFields{k})

        error( ...
            'Input MAT file lacks field: %s', ...
            requiredFields{k});

    end

end


subjectsAll = string(S.subjects(:));
groupsAll   = string(S.groups(:));

regionNames = string(S.regionNames(:));

edgeNames   = string(S.edgeNames(:));
edgeRegion1 = string(S.edgeRegion1(:));
edgeRegion2 = string(S.edgeRegion2(:));

edgeIndex1 = double(S.edgeIndex1(:));
edgeIndex2 = double(S.edgeIndex2(:));

bandNamesAll = string(S.bandNames(:));

deltaBio = double(S.deltaBio);

completeMaskSaved = ...
    logical(S.completeNetworkMask(:));

nEpochMatchedAll = ...
    double(S.nEpochMatched(:));


%% =========================================================================
% 4. HARD STRUCTURAL CHECKS
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('STRUCTURAL CHECKS\n');
fprintf('============================================================\n');


if ~isequal(size(deltaBio),[130 55 3])

    error( ...
        'Expected deltaBio = 130 x 55 x 3. Found %s.', ...
        mat2str(size(deltaBio)));

end


if numel(regionNames) ~= N_NODES

    error( ...
        'Expected 11 regional nodes; found %d.', ...
        numel(regionNames));

end


if numel(edgeNames) ~= N_EDGES

    error( ...
        'Expected 55 edges; found %d.', ...
        numel(edgeNames));

end


if numel(bandNamesAll) < 3 || ...
   ~isequal( ...
       lower(bandNamesAll(1:3)), ...
       BIO_BANDS_EXPECTED)

    error( ...
        'First three bands must be theta, alpha, beta.');

end


% Recompute complete-network mask directly.
completeMaskRecomputed = all( ...
    isfinite( ...
        reshape( ...
            deltaBio, ...
            size(deltaBio,1), ...
            N_EDGES*N_BANDS)), ...
    2);


if ~isequal( ...
        completeMaskSaved, ...
        completeMaskRecomputed)

    error([ ...
        'Saved completeNetworkMask does not equal ' ...
        'the direct finite-data mask.']);

end


nComplete = sum(completeMaskSaved);

nHC = sum( ...
    completeMaskSaved & groupsAll=="HC");

nPD = sum( ...
    completeMaskSaved & groupsAll=="PD");


fprintf('Complete N = %d\n',nComplete);
fprintf('HC         = %d\n',nHC);
fprintf('PD         = %d\n',nPD);


if nComplete ~= N_EXPECTED || ...
   nHC ~= N_HC_EXPECTED || ...
   nPD ~= N_PD_EXPECTED

    error( ...
        'Expected complete cohort N=117 = 22 HC + 95 PD.');

end


subjects = subjectsAll(completeMaskSaved);
groups   = groupsAll(completeMaskSaved);

deltaNBS = ...
    deltaBio(completeMaskSaved,:,:);

nEpochMatched = ...
    nEpochMatchedAll(completeMaskSaved);


if any(~isfinite(deltaNBS),'all')

    error( ...
        'Nonfinite deltaBio remains in complete-network cohort.');

end


if any(nEpochMatched ~= 58)

    warning([ ...
        'At least one complete-network subject does not have ' ...
        'exactly 58 matched epochs.']);

end


N = numel(subjects);


% --------------------------------------------------------------
% Exact STEP 9 ordering after reshape:
%
% columns   1:55   = theta
% columns  56:110  = alpha
% columns 111:165  = beta
% --------------------------------------------------------------

Y = reshape( ...
    deltaNBS, ...
    N, ...
    N_EDGES*N_BANDS);


fprintf('Outcome matrix = %d x %d\n', ...
    size(Y,1),size(Y,2));


%% =========================================================================
% 5. LOAD AGE AND SEX
%% =========================================================================

if ~exist(participantsFile,'file')

    error( ...
        'participants.tsv not found:\n%s', ...
        participantsFile);

end


P = readtable( ...
    participantsFile, ...
    'FileType','text', ...
    'Delimiter','\t', ...
    'TextType','string');


neededColumns = [ ...
    "participant_id"
    "group"
    "age"
    "sex"];


pVars = string(P.Properties.VariableNames);


for k = 1:numel(neededColumns)

    if ~ismember(neededColumns(k),pVars)

        error( ...
            'participants.tsv lacks column: %s', ...
            neededColumns(k));

    end

end


participantID = ...
    string(P.participant_id);


[tf,loc] = ...
    ismember(subjects,participantID);


if ~all(tf)

    disp(subjects(~tf));

    error( ...
        'Could not align all 117 subjects.');

end


participantGroup = ...
    string(P.group(loc));


if ~isequal( ...
        participantGroup, ...
        groups)

    error( ...
        'Group mismatch between connectivity and participants.tsv.');

end


age = column_to_double( ...
    P.age(loc));


if any(~isfinite(age))

    error( ...
        'Missing/nonfinite age.');

end


sexRaw = ...
    upper( ...
        strtrim( ...
            string(P.sex(loc))));


if any( ...
        ~ismember( ...
            sexRaw, ...
            ["F","M"]))

    error( ...
        'Sex must be F or M.');

end


%% =========================================================================
% 6. EXACT STEP 9 DESIGN
%% =========================================================================

Group = ...
    double(groups=="PD");

Sex = ...
    double(sexRaw=="M");

Age_c = ...
    age - mean(age);


% Full model:
%
% Delta =
%   intercept + Group + Age_c + Sex
%
M = [ ...
    ones(N,1), ...
    Group, ...
    Age_c, ...
    Sex];


% Reduced nuisance model:
%
% Delta =
%   intercept + Age_c + Sex
%
Z = [ ...
    ones(N,1), ...
    Age_c, ...
    Sex];


if rank(M) ~= size(M,2)

    error( ...
        'Full design is rank deficient.');

end


if rank(Z) ~= size(Z,2)

    error( ...
        'Reduced design is rank deficient.');

end


C = [0;1;0;0];

groupColumn = 2;


Mpinv = pinv(M);
Zpinv = pinv(Z);


vgHC = ...
    Group==0;

vgPD = ...
    Group==1;


% Same variance-group quantities as STEP 9.
Hfull = ...
    M*Mpinv;

Rfull = ...
    eye(N)-Hfull;

Rdiag = ...
    diag(Rfull);


sumR_HC = ...
    sum(Rdiag(vgHC));

sumR_PD = ...
    sum(Rdiag(vgPD));


A_HC = ...
    M(vgHC,:)'*M(vgHC,:);

A_PD = ...
    M(vgPD,:)'*M(vgPD,:);


if sumR_HC<=0 || sumR_PD<=0

    error( ...
        'Invalid variance-group residual df.');

end


fprintf('\nDesign reproduced:\n');

fprintf( ...
    'Full    = Intercept + Group + Age_c + Sex\n');

fprintf( ...
    'Reduced = Intercept + Age_c + Sex\n');


%% =========================================================================
% 7. OBSERVED HETEROSCEDASTIC v
%% =========================================================================

[vObservedVec,betaObservedVec] = ...
    compute_signed_v_all( ...
        Y, ...
        M, ...
        Mpinv, ...
        C, ...
        groupColumn, ...
        vgHC, ...
        vgPD, ...
        sumR_HC, ...
        sumR_PD, ...
        A_HC, ...
        A_PD);


if any(~isfinite(vObservedVec))

    error( ...
        'Observed v contains NaN/Inf.');

end


vObserved = ...
    reshape( ...
        vObservedVec, ...
        N_EDGES, ...
        N_BANDS);


betaObserved = ...
    reshape( ...
        betaObservedVec, ...
        N_EDGES, ...
        N_BANDS);


%% =========================================================================
% 8. START PARALLEL POOL
%% =========================================================================

useParallelNow = false;


if USE_PARALLEL && ...
   license('test','Distrib_Computing_Toolbox')

    pool = ...
        gcp('nocreate');


    if isempty(pool)

        pool = ...
            parpool( ...
                'local', ...
                N_WORKERS);


    elseif pool.NumWorkers ~= N_WORKERS

        delete(pool);

        pool = ...
            parpool( ...
                'local', ...
                N_WORKERS);

    end


    useParallelNow = true;


    fprintf( ...
        '\nParallel workers = %d\n', ...
        pool.NumWorkers);

else

    fprintf( ...
        '\nRunning sequentially.\n');

end


%% =========================================================================
% PART A
% THRESHOLD SENSITIVITY
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('PART A — NBS THRESHOLD SENSITIVITY\n');
fprintf('============================================================\n');


% Reduced-model values exactly as used in STEP 9.
B_reduced = ...
    Zpinv*Y;

FittedReduced = ...
    Z*B_reduced;

ResidualReduced = ...
    Y-FittedReduced;


clear B_reduced;


nThresholds = ...
    numel(THRESHOLDS);


% --------------------------------------------------------------
% Observed largest joint component at each threshold.
% --------------------------------------------------------------

observedJointMax = ...
    zeros(nThresholds,1);


thetaNegativeExtent = ...
    zeros(nThresholds,1);


for t = 1:nThresholds

    threshold = ...
        THRESHOLDS(t);


    observedJointMax(t) = ...
        joint_max_component_extent( ...
            vObservedVec, ...
            N_EDGES, ...
            N_BANDS, ...
            threshold, ...
            edgeIndex1, ...
            edgeIndex2, ...
            N_NODES);


    thetaNegComponents = ...
        find_nbs_components( ...
            vObserved(:,1), ...
            -1, ...
            threshold, ...
            edgeIndex1, ...
            edgeIndex2, ...
            N_NODES);


    if isempty(thetaNegComponents)

        thetaNegativeExtent(t) = 0;

    else

        thetaNegativeExtent(t) = ...
            max( ...
                [thetaNegComponents.extent]);

    end

end


fprintf('\nObserved extents:\n');


for t = 1:nThresholds

    fprintf([ ...
        '|v| > %.1f : ' ...
        'theta-negative max = %d; ' ...
        'joint max = %d\n'], ...
        THRESHOLDS(t), ...
        thetaNegativeExtent(t), ...
        observedJointMax(t));

end


% --------------------------------------------------------------
% Generate exactly the same Rademacher sequence family as STEP 9.
% --------------------------------------------------------------

rng( ...
    THRESHOLD_SEED, ...
    'twister');


signMatrix = ...
    int8( ...
        ones( ...
            N_THRESHOLD_RESAMPLES, ...
            N));


flipMask = ...
    rand( ...
        N_THRESHOLD_RESAMPLES, ...
        N) < 0.5;


signMatrix(flipMask) = -1;

clear flipMask;


nullMaxByThreshold = ...
    zeros( ...
        N_THRESHOLD_RESAMPLES, ...
        nThresholds);


thresholdTimer = tic;


if useParallelNow

    parfor b = 1:N_THRESHOLD_RESAMPLES

        signs = ...
            double( ...
                signMatrix(b,:))';


        Ystar = ...
            FittedReduced + ...
            ResidualReduced.*signs;


        vStar = ...
            compute_signed_v_all_only( ...
                Ystar, ...
                M, ...
                Mpinv, ...
                C, ...
                groupColumn, ...
                vgHC, ...
                vgPD, ...
                sumR_HC, ...
                sumR_PD, ...
                A_HC, ...
                A_PD);


        tmp = ...
            zeros(1,nThresholds);


        for t = 1:nThresholds

            tmp(t) = ...
                joint_max_component_extent( ...
                    vStar, ...
                    N_EDGES, ...
                    N_BANDS, ...
                    THRESHOLDS(t), ...
                    edgeIndex1, ...
                    edgeIndex2, ...
                    N_NODES);

        end


        nullMaxByThreshold(b,:) = ...
            tmp;

    end


else

    for b = 1:N_THRESHOLD_RESAMPLES

        signs = ...
            double( ...
                signMatrix(b,:))';


        Ystar = ...
            FittedReduced + ...
            ResidualReduced.*signs;


        vStar = ...
            compute_signed_v_all_only( ...
                Ystar, ...
                M, ...
                Mpinv, ...
                C, ...
                groupColumn, ...
                vgHC, ...
                vgPD, ...
                sumR_HC, ...
                sumR_PD, ...
                A_HC, ...
                A_PD);


        for t = 1:nThresholds

            nullMaxByThreshold(b,t) = ...
                joint_max_component_extent( ...
                    vStar, ...
                    N_EDGES, ...
                    N_BANDS, ...
                    THRESHOLDS(t), ...
                    edgeIndex1, ...
                    edgeIndex2, ...
                    N_NODES);

        end

    end

end


fprintf( ...
    '\nThreshold analysis finished in %.2f h.\n', ...
    toc(thresholdTimer)/3600);


% --------------------------------------------------------------
% Corrected p-values.
% --------------------------------------------------------------

thetaNegativeP = ...
    ones(nThresholds,1);


jointMaximumP = ...
    ones(nThresholds,1);


null95 = ...
    nan(nThresholds,1);


for t = 1:nThresholds

    if thetaNegativeExtent(t)>0

        thetaNegativeP(t) = ...
            ( ...
            1 + ...
            sum( ...
                nullMaxByThreshold(:,t) >= ...
                thetaNegativeExtent(t)) ...
            ) / ...
            (N_THRESHOLD_RESAMPLES+1);

    end


    if observedJointMax(t)>0

        jointMaximumP(t) = ...
            ( ...
            1 + ...
            sum( ...
                nullMaxByThreshold(:,t) >= ...
                observedJointMax(t)) ...
            ) / ...
            (N_THRESHOLD_RESAMPLES+1);

    end


    null95(t) = ...
        empirical_percentile( ...
            nullMaxByThreshold(:,t), ...
            0.95);

end


ThresholdSensitivity = ...
    table( ...
        THRESHOLDS(:), ...
        thetaNegativeExtent, ...
        thetaNegativeP, ...
        observedJointMax, ...
        jointMaximumP, ...
        null95, ...
        'VariableNames',{ ...
        'Threshold', ...
        'ThetaNegativeExtent', ...
        'ThetaNegativeJointFWER_P', ...
        'ObservedJointMaximumExtent', ...
        'ObservedJointMaximumFWER_P', ...
        'Null95thPercentileExtent'});


fprintf('\nTHRESHOLD SENSITIVITY RESULTS\n');

disp(ThresholdSensitivity);


writetable( ...
    ThresholdSensitivity, ...
    fullfile( ...
        outRoot, ...
        sprintf( ...
            'Paper3_NBS_threshold_sensitivity_%s.csv', ...
            char(RUN_MODE))));


%% =========================================================================
% CHECK ORIGINAL 2.5 RESULT
%% =========================================================================

idxPrimary = ...
    find( ...
        abs(THRESHOLDS-2.5)<1e-12, ...
        1);


if isempty(idxPrimary)

    error( ...
        'Primary threshold 2.5 missing.');

end


fprintf('\nPrimary-threshold reproduction check:\n');

fprintf( ...
    'Theta-negative extent = %d\n', ...
    thetaNegativeExtent(idxPrimary));

fprintf( ...
    'Joint FWER p          = %.6f\n', ...
    thetaNegativeP(idxPrimary));


if RUN_MODE=="final"

    if thetaNegativeExtent(idxPrimary) ~= 32

        warning([ ...
            'FINAL validation did not reproduce the original ' ...
            '32-edge theta-negative component. Investigate.']);

    end

end


%% =========================================================================
% PART B
% EMPIRICAL NULL CALIBRATION
%% =========================================================================

fprintf('\n============================================================\n');
fprintf('PART B — EMPIRICAL NULL FWER CALIBRATION\n');
fprintf('============================================================\n');


% -------------------------------------------------------------------------
% TRUE NULL MEAN:
%
% Intercept + Age_c + Sex only.
%
% Therefore there is no adjusted Group term in the data-generating model.
% -------------------------------------------------------------------------

B_null = ...
    Zpinv*Y;


FittedNull = ...
    Z*B_null;


% -------------------------------------------------------------------------
% NOISE MODEL
%
% Fit full observed model first. This removes the observed Group effect
% before estimating the noise distributions.
% -------------------------------------------------------------------------

B_full = ...
    Mpinv*Y;


E_full = ...
    Y-M*B_full;


% -------------------------------------------------------------------------
% HC2 leverage correction for DATA GENERATION only.
%
% This does NOT change the primary v statistic.
% -------------------------------------------------------------------------

leverage = ...
    diag(Hfull);


hc2Denominator = ...
    sqrt( ...
        max( ...
            1-leverage, ...
            eps));


E_hc2 = ...
    E_full ./ ...
    hc2Denominator;


% -------------------------------------------------------------------------
% Separate HC and PD residual pools.
%
% This preserves heteroscedasticity rather than forcing common variance.
% -------------------------------------------------------------------------

E_HC = ...
    E_hc2(vgHC,:);


E_PD = ...
    E_hc2(vgPD,:);


% Recenter each outcome within group.
E_HC = ...
    E_HC - ...
    mean(E_HC,1);


E_PD = ...
    E_PD - ...
    mean(E_PD,1);


% -------------------------------------------------------------------------
% Describe amount of observed heteroscedasticity.
% -------------------------------------------------------------------------

varHC = ...
    var(E_HC,0,1);


varPD = ...
    var(E_PD,0,1);


validVar = ...
    isfinite(varHC) & ...
    isfinite(varPD) & ...
    varHC>0;


varianceRatio = ...
    varPD(validVar) ./ ...
    varHC(validVar);


fprintf('\nResidual variance ratio PD/HC across 165 outcomes:\n');

fprintf( ...
    'Median = %.3f\n', ...
    median(varianceRatio));

fprintf( ...
    'IQR    = [%.3f, %.3f]\n', ...
    empirical_percentile(varianceRatio,0.25), ...
    empirical_percentile(varianceRatio,0.75));


%% =========================================================================
% 9. OUTER NULL SIMULATIONS
%% =========================================================================

simulationP = ...
    nan(N_OUTER_SIMULATIONS,1);


simulationObservedMax = ...
    nan(N_OUTER_SIMULATIONS,1);


simulationReject = ...
    false(N_OUTER_SIMULATIONS,1);


simTimer = tic;


if useParallelNow

    parfor s = 1:N_OUTER_SIMULATIONS

        [ ...
            simulationP(s), ...
            simulationObservedMax(s) ...
        ] = ...
            run_one_null_simulation( ...
                SIMULATION_SEED+s, ...
                FittedNull, ...
                E_HC, ...
                E_PD, ...
                vgHC, ...
                vgPD, ...
                M, ...
                Z, ...
                Mpinv, ...
                Zpinv, ...
                C, ...
                groupColumn, ...
                sumR_HC, ...
                sumR_PD, ...
                A_HC, ...
                A_PD, ...
                N_INNER_RESAMPLES, ...
                PRIMARY_THRESHOLD, ...
                N_EDGES, ...
                N_BANDS, ...
                edgeIndex1, ...
                edgeIndex2, ...
                N_NODES);


        simulationReject(s) = ...
            simulationP(s) < ...
            ALPHA_FWER;

    end


else

    progressStep = ...
        max( ...
            1, ...
            round( ...
                N_OUTER_SIMULATIONS/20));


    for s = 1:N_OUTER_SIMULATIONS

        [ ...
            simulationP(s), ...
            simulationObservedMax(s) ...
        ] = ...
            run_one_null_simulation( ...
                SIMULATION_SEED+s, ...
                FittedNull, ...
                E_HC, ...
                E_PD, ...
                vgHC, ...
                vgPD, ...
                M, ...
                Z, ...
                Mpinv, ...
                Zpinv, ...
                C, ...
                groupColumn, ...
                sumR_HC, ...
                sumR_PD, ...
                A_HC, ...
                A_PD, ...
                N_INNER_RESAMPLES, ...
                PRIMARY_THRESHOLD, ...
                N_EDGES, ...
                N_BANDS, ...
                edgeIndex1, ...
                edgeIndex2, ...
                N_NODES);


        simulationReject(s) = ...
            simulationP(s) < ...
            ALPHA_FWER;


        if mod(s,progressStep)==0

            fprintf([ ...
                'Simulation %d/%d | ' ...
                'current empirical FWER = %.4f\n'], ...
                s, ...
                N_OUTER_SIMULATIONS, ...
                mean( ...
                    simulationReject(1:s)));

        end

    end

end


simulationHours = ...
    toc(simTimer)/3600;


%% =========================================================================
% 10. EMPIRICAL FWER
%% =========================================================================

nFalsePositive = ...
    sum(simulationReject);


empiricalFWER = ...
    mean(simulationReject);


mcSE = ...
    sqrt( ...
        empiricalFWER * ...
        (1-empiricalFWER) / ...
        N_OUTER_SIMULATIONS);


[wilsonLow,wilsonHigh] = ...
    wilson_interval( ...
