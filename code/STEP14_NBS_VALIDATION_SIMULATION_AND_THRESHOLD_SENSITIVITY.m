function [pFWER,observedMax] = ...
    run_one_null_simulation( ...
        seed, ...
        FittedNull, ...
        E_HC, ...
        E_PD, ...
        vgHC, ...
        vgPD, ...
        M, ...
        Z, ...
        Mpinv, ...
        Zpinv, ...
        C, ...
        groupColumn, ...
        sumR_HC, ...
        sumR_PD, ...
        A_HC, ...
        A_PD, ...
        nInner, ...
        threshold, ...
        nEdges, ...
        nBands, ...
        edgeIndex1, ...
        edgeIndex2, ...
        nNodes)


    N = ...
        size(M,1);


    K = ...
        size(FittedNull,2);


    % Independent deterministic RNG for this outer simulation.
    rs = ...
        RandStream( ...
            'mt19937ar', ...
            'Seed', ...
            seed);


    % --------------------------------------------------------------
    % Generate synthetic errors.
    %
    % Entire subject residual vectors are resampled, preserving
    % cross-edge and cross-band covariance.
    % --------------------------------------------------------------

    ESim = ...
        zeros(N,K);


    nHC = ...
        sum(vgHC);


    nPD = ...
        sum(vgPD);


    idxHC = ...
        randi( ...
            rs, ...
            size(E_HC,1), ...
            nHC, ...
            1);


    idxPD = ...
        randi( ...
            rs, ...
            size(E_PD,1), ...
            nPD, ...
            1);


    ESim(vgHC,:) = ...
        E_HC(idxHC,:);


    ESim(vgPD,:) = ...
        E_PD(idxPD,:);


    % --------------------------------------------------------------
    % Random subject-level sign.
    %
    % This creates a symmetric null-error distribution while retaining
    % the empirical multivariate residual magnitudes and covariance.
    % --------------------------------------------------------------

    generatorSigns = ...
        2 * ...
        (rand(rs,N,1)>=0.5) ...
        - 1;


    ESim = ...
        ESim .* ...
        generatorSigns;


    % True adjusted Group effect = zero.
    YSim = ...
        FittedNull + ...
        ESim;


    % --------------------------------------------------------------
    % Observed statistic for this synthetic null dataset.
    % --------------------------------------------------------------

    vObs = ...
        compute_signed_v_all_only( ...
            YSim, ...
            M, ...
            Mpinv, ...
            C, ...
            groupColumn, ...
            vgHC, ...
            vgPD, ...
            sumR_HC, ...
            sumR_PD, ...
            A_HC, ...
            A_PD);


    observedMax = ...
        joint_max_component_extent( ...
            vObs, ...
            nEdges, ...
            nBands, ...
            threshold, ...
            edgeIndex1, ...
            edgeIndex2, ...
            nNodes);


    if observedMax==0

        pFWER = 1;

        return;

    end


    % --------------------------------------------------------------
    % Exact same reduced-model residual sign-flip procedure applied to
    % this synthetic null dataset.
    % --------------------------------------------------------------

    Bred = ...
        Zpinv*YSim;


    FittedRed = ...
        Z*Bred;


    ResidRed = ...
        YSim-FittedRed;


    nullMax = ...
        zeros(nInner,1);


    for b = 1:nInner

        signs = ...
            2 * ...
            (rand(rs,N,1)>=0.5) ...
            - 1;


        Ystar = ...
            FittedRed + ...
            ResidRed.*signs;


        vStar = ...
            compute_signed_v_all_only( ...
                Ystar, ...
                M, ...
                Mpinv, ...
                C, ...
                groupColumn, ...
                vgHC, ...
                vgPD, ...
                sumR_HC, ...
                sumR_PD, ...
                A_HC, ...
                A_PD);


        nullMax(b) = ...
            joint_max_component_extent( ...
                vStar, ...
                nEdges, ...
                nBands, ...
                threshold, ...
                edgeIndex1, ...
                edgeIndex2, ...
                nNodes);

    end


    pFWER = ...
        ( ...
        1 + ...
        sum( ...
            nullMax >= observedMax) ...
        ) / ...
        (nInner+1);

end


