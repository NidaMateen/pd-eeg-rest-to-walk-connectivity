%% =========================================================================
% PAPER 3 — STEP 14
% VALIDATION OF PRIMARY NBS INFERENCE
%
% Empirical null calibration + NBS threshold sensitivity
%
% IMPORTANT
% ---------
% This is a ROBUSTNESS / VALIDATION analysis.
% It DOES NOT replace or modify the frozen STEP 9 primary analysis.
%
% PART A
% ------
% Repeat the observed NBS at:
%   |v| > 2.0
%   |v| > 2.5  <-- ORIGINAL PRIMARY THRESHOLD
%   |v| > 3.0
%
% using the same:
%   - N = 117 = 22 HC + 95 PD
%   - Group + Age_c + Sex model
%   - heteroscedastic signed v statistic
%   - reduced-model Freedman-Lane sign flipping
%   - joint maximum across:
%       theta+, theta-, alpha+, alpha-, beta+, beta-
%
% PART B
% ------
% Empirically test Type-I error under a true Group-null model while
% preserving:
%   - actual sample-size imbalance
%   - actual age and sex
%   - separate HC/PD residual variance structures
%   - cross-edge dependence
%   - cross-band dependence
%
% Synthetic null datasets contain NO adjusted Group effect.
%
% Entire 165-outcome residual vectors are resampled by subject, so the
% dependence between the 55 edges and 3 bands is retained.
%
% Residual signs are randomized during null-data generation to produce
% symmetric errors, matching the assumption underlying Rademacher
% sign flipping.
%% =========================================================================

clear;
clc;
close all;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();

%% =========================================================================
% 1. SETTINGS
%% =========================================================================

datasetRoot = ...
    cfg.datasetRoot;

connectivityRoot = fullfile( ...
    datasetRoot, ...
    'PAPER3_FINAL_CONNECTIVITY');

statsInputFile = fullfile( ...
    connectivityRoot, ...
    'Paper3_CONNECTIVITY_STATS_INPUT.mat');

participantsFile = fullfile( ...
    datasetRoot, ...
    'participants.tsv');

outRoot = fullfile( ...
    datasetRoot, ...
    'PAPER3_NBS_VALIDATION');

if ~exist(outRoot,'dir')
    mkdir(outRoot);
end


% -------------------------------------------------------------------------
% RUN PILOT FIRST.
% After the pilot completes correctly, change this to "final".
% -------------------------------------------------------------------------

RUN_MODE = "final";


USE_PARALLEL = true;
N_WORKERS = 2;


% Sensitivity thresholds.
% 2.5 remains the frozen primary threshold.
THRESHOLDS = [2.0 2.5 3.0];

PRIMARY_THRESHOLD = 2.5;

ALPHA_FWER = 0.05;


% Use the original primary seed for threshold sensitivity.
% Therefore the FINAL |v|>2.5 analysis should reproduce STEP 9.
THRESHOLD_SEED = 20260916;


% Separate deterministic seed family for simulation.
SIMULATION_SEED = 20261013;


switch lower(RUN_MODE)

    case "pilot"

        % Quick validation that everything works.
        % Do not use these numbers in the manuscript.
        N_THRESHOLD_RESAMPLES = 2000;

        N_OUTER_SIMULATIONS = 100;
        N_INNER_RESAMPLES   = 199;


    case "final"

        % Manuscript-quality threshold sensitivity.
        N_THRESHOLD_RESAMPLES = 10000;

        % Empirical calibration.
        %
        % 500 outer null datasets gives a useful estimate of whether
        % FWER is grossly inflated while keeping computation practical.
        %
        % 499 inner resamples gives approximately 0.002 p-value resolution.
        N_OUTER_SIMULATIONS = 1000;
        N_INNER_RESAMPLES   = 999;


    otherwise

        error('RUN_MODE must be "pilot" or "final".');

end


fprintf('\n============================================================\n');
fprintf('PAPER 3 NBS VALIDATION\n');
fprintf('============================================================\n');

fprintf('Mode                       : %s\n',char(RUN_MODE));
fprintf('Threshold resamples        : %d\n',N_THRESHOLD_RESAMPLES);
fprintf('Outer null simulations     : %d\n',N_OUTER_SIMULATIONS);
fprintf('Inner resamples/simulation : %d\n',N_INNER_RESAMPLES);


%% =========================================================================
% 2. EXPECTED STUDY STRUCTURE
