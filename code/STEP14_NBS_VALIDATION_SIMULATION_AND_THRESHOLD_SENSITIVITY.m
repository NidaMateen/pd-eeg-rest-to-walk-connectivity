function [v,betaGroup] = ...
    compute_signed_v_all( ...
        Y, ...
        M, ...
        Mpinv, ...
        C, ...
        groupColumn, ...
        vgHC, ...
        vgPD, ...
        sumR_HC, ...
        sumR_PD, ...
        A_HC, ...
        A_PD)


    Bhat = ...
        Mpinv*Y;


    E = ...
        Y-M*Bhat;


    sseHC = ...
        sum( ...
            E(vgHC,:).^2, ...
            1);


    ssePD = ...
        sum( ...
            E(vgPD,:).^2, ...
            1);


    if any(sseHC<=0) || ...
       any(ssePD<=0)

        error( ...
            'Nonpositive variance-group SSE.');

    end


    wHC = ...
        sumR_HC ./ ...
        sseHC;


    wPD = ...
        sumR_PD ./ ...
        ssePD;


    betaGroup = ...
        Bhat(groupColumn,:);


    K = ...
        size(Y,2);


    v = ...
        nan(1,K);


    for k = 1:K

        MtWM = ...
            wHC(k)*A_HC + ...
            wPD(k)*A_PD;


        q = ...
            C' * ...
            (MtWM\C);


        if ~isfinite(q) || q<=0

            error( ...
                'Invalid heteroscedastic contrast variance.');

        end


        v(k) = ...
            betaGroup(k) / ...
            sqrt(q);

    end

end


