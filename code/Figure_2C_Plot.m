%% ========================================================================
% PAPER 3 — FIGURE 2C
%
% Condition-level characterization of the significant
% 32-edge theta-band NBS component
%
% Primary complete-network cohort:
%       HC = 22
%       PD = 95
%
% Frozen component-average values:
%
% HC:
%       Rest = 0.003128
%       Walk = 0.070769
%       Delta = 0.067641
%
% PD:
%       Rest = 0.019160
%       Walk = 0.040341
%       Delta = 0.021181
%
% PURPOSE:
% Descriptive visualization of the Rest-to-Walk pattern underlying
% the significant theta-band reconfiguration effect.
%
% IMPORTANT:
% This panel is descriptive.
% Confirmatory inference remains the component-level NBS result.
%
% No panel letter or title is added here.
% Add "c" later in PowerPoint.
% ========================================================================

clear;
close all;
clc;


% Repository path configuration (machine-specific paths are not stored in this file).
cfg = paper3_config();

%% ========================================================================
% 1. FROZEN CONDITION MEANS
% ========================================================================

HC_rest = 0.003128;
HC_walk = 0.070769;

PD_rest = 0.019160;
PD_walk = 0.040341;

nHC = 22;
nPD = 95;

%% ========================================================================
% 2. INTERNAL CONSISTENCY CHECK
% ========================================================================

HC_delta = HC_walk - HC_rest;
PD_delta = PD_walk - PD_rest;

fprintf('\n============================================================\n');
fprintf('FIGURE 2C DATA CHECK\n');
fprintf('============================================================\n');

fprintf('HC Rest  = %.6f\n',HC_rest);
fprintf('HC Walk  = %.6f\n',HC_walk);
fprintf('HC Delta = %.6f\n\n',HC_delta);

fprintf('PD Rest  = %.6f\n',PD_rest);
fprintf('PD Walk  = %.6f\n',PD_walk);
fprintf('PD Delta = %.6f\n\n',PD_delta);

assert(abs(HC_delta - 0.067641) < 1e-6, ...
    'HC condition means do not reproduce frozen Delta.');

assert(abs(PD_delta - 0.021181) < 1e-6, ...
    'PD condition means do not reproduce frozen Delta.');

fprintf('PASS: condition means reproduce frozen Delta values.\n');
fprintf('============================================================\n\n');

%% ========================================================================
% 3. VISUAL SETTINGS
% ========================================================================

fontName = 'Times New Roman';

% Same group colors as Panel B
HCcolor = [0.30 0.30 0.30];
PDcolor = [0.36 0.55 0.78];

xRest = 1;
xWalk = 2;

%% ========================================================================
% 4. CREATE FIGURE
% ========================================================================

fig = figure( ...
    'Color','w', ...
    'Units','centimeters', ...
    'Position',[2 2 9.5 10.0], ...
    'Renderer','painters');

ax = axes(fig);

hold(ax,'on');

%% ========================================================================
% 5. ZERO REFERENCE LINE
% ========================================================================

yline(ax,0,'--', ...
    'Color',[0.70 0.70 0.70], ...
    'LineWidth',1.1);

%% ========================================================================
% 6. HC REST -> WALK
% ========================================================================

% Connecting line
plot(ax, ...
    [xRest xWalk], ...
    [HC_rest HC_walk], ...
    '-', ...
    'Color',HCcolor, ...
    'LineWidth',2.8);

% HC Rest = open circle
scatter(ax, ...
    xRest,HC_rest, ...
    115,'o', ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor',HCcolor, ...
    'LineWidth',2.2);

% HC Walk = filled circle
scatter(ax, ...
    xWalk,HC_walk, ...
    115,'o', ...
    'MarkerFaceColor',HCcolor, ...
    'MarkerEdgeColor',HCcolor, ...
    'LineWidth',2.2);

%% ========================================================================
% 7. PD REST -> WALK
% ========================================================================

% Connecting line
plot(ax, ...
    [xRest xWalk], ...
    [PD_rest PD_walk], ...
    '-', ...
    'Color',PDcolor, ...
    'LineWidth',2.8);

% PD Rest = open circle
scatter(ax, ...
    xRest,PD_rest, ...
    115,'o', ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor',PDcolor, ...
    'LineWidth',2.2);

% PD Walk = filled circle
scatter(ax, ...
    xWalk,PD_walk, ...
    115,'o', ...
    'MarkerFaceColor',PDcolor, ...
    'MarkerEdgeColor',PDcolor, ...
    'LineWidth',2.2);

%% ========================================================================
% 8. DIRECT GROUP LABELS
%
% Keep only HC and PD here.
% Sample sizes are already shown in Panel B and can also be stated
% in the figure caption.
% ========================================================================

text(ax, ...
    2.06,HC_walk, ...
    'HC', ...
    'FontName',fontName, ...
    'FontSize',13, ...
    'FontWeight','bold', ...
    'Color',HCcolor, ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','middle');

text(ax, ...
    2.06,PD_walk, ...
    'PD', ...
    'FontName',fontName, ...
    'FontSize',13, ...
    'FontWeight','bold', ...
    'Color',PDcolor, ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','middle');

%% ========================================================================
% 9. DELTA ANNOTATIONS
%
% Positioned away from the crossing point.
% ========================================================================

text(ax, ...
    1.42,0.0525, ...
    sprintf('\\Delta = %.3f',HC_delta), ...
    'FontName',fontName, ...
    'FontSize',11.5, ...
    'FontWeight','bold', ...
    'Color',HCcolor, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle');

text(ax, ...
    1.62,0.0175, ...
    sprintf('\\Delta = %.3f',PD_delta), ...
    'FontName',fontName, ...
    'FontSize',11.5, ...
    'FontWeight','bold', ...
    'Color',PDcolor, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle');

%% ========================================================================
% 10. AXIS LIMITS
% ========================================================================

% Extra room on right for direct labels
xlim(ax,[0.72 2.30]);

ylim(ax,[-0.01 0.085]);

%% ========================================================================
% 11. X-AXIS
% ========================================================================

ax.XTick = [1 2];

ax.XTickLabel = { ...
    'Rest', ...
    'Walk'};

%% ========================================================================
% 12. Y-AXIS
% ========================================================================

ylabel(ax, ...
    'Component-average theta db-wPLI', ...
    'FontName',fontName, ...
    'FontSize',13, ...
    'FontWeight','bold', ...
    'Color','k');

yticks(ax,[0 0.02 0.04 0.06 0.08]);

ytickformat(ax,'%.2f');

%% ========================================================================
% 13. AXIS TYPOGRAPHY
% ========================================================================

set(ax, ...
    'FontName',fontName, ...
    'FontSize',12, ...
    'FontWeight','bold', ...
    'LineWidth',1.4, ...
    'TickDir','out', ...
    'TickLength',[0.018 0.018], ...
    'Box','off', ...
    'XColor','k', ...
    'YColor','k');

ax.XGrid = 'off';
ax.YGrid = 'off';

%% ========================================================================
% 14. COMPACT LAYOUT
% ========================================================================

ax.Position = [0.22 0.13 0.72 0.83];

%% ========================================================================
% 15. EXPORT
% ========================================================================

outputFolder = ...
    fullfile(cfg.datasetRoot,'PAPER3_PRIMARY_NBS');

if ~exist(outputFolder,'dir')
    warning('Expected output directory not found. Saving to current folder.');
    outputFolder = pwd;
end

pdfFile = fullfile( ...
    outputFolder, ...
    'Figure2C_Theta_Rest_Walk_Means_FINAL_v2.pdf');

pngFile = fullfile( ...
    outputFolder, ...
    'Figure2C_Theta_Rest_Walk_Means_FINAL_v2_600dpi.png');

exportgraphics(fig, ...
    pdfFile, ...
    'ContentType','vector', ...
    'BackgroundColor','white');

exportgraphics(fig, ...
    pngFile, ...
    'Resolution',600, ...
    'BackgroundColor','white');

fprintf('\nFigure saved:\n');
fprintf('%s\n',pdfFile);
fprintf('%s\n',pngFile);